"""BANK V2: a plain-English report of the deep scan (scan_history.py's atlas), for the owner.

Per setup, over every clean or ambiguous instance in the top 1,000 stocks by dollar volume that session since 1995:
how many there are, how they spread over eras, market conditions and sectors, how often the finder's must-work verdict
passed (the share of qualifying instances that worked), the median culmination and how often the signal low broke,
and which other setups fire on the same bar (the "both count?" questions for his rulings). Read-only; writes Markdown.

  python scripts/study/bank_v2/atlas_report.py --atlas <atlas.jsonl.gz> --out docs/study/bank_v2/ATLAS.md
"""
from __future__ import annotations

import argparse
import gzip
import json
import pathlib
import statistics
from collections import Counter

NAMES = {"setup.family3.kicker": "Kicker", "setup.family4.oops": "Oops Reversal", "setup.family3.gap_support": "Gap Support",
         "setup.family3.hve": "High Volume Edge", "setup.family4.slingshot": "Slingshot", "setup.family1.launchpad": "Launchpad",
         "setup.family3.bear_gap": "Bear gap"}
ERAS = [(1995, 1999), (2000, 2004), (2005, 2009), (2010, 2014), (2015, 2019), (2020, 2026)]


def era(t):
    y = int(str(t)[:4])
    return next((f"{a}-{str(b)[2:]}" for a, b in ERAS if a <= y <= b), "other")


def pct(n, d):
    return f"{round(100 * n / d)}%" if d else "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atlas", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--top", type=int, default=1000)
    ap.add_argument("--scanned", type=int, default=0, help="how many stocks the scan read (its own log line)")
    a = ap.parse_args()
    rows = [json.loads(l) for l in gzip.open(a.atlas, "rt", encoding="utf-8")]
    inst = [r for r in rows if (r.get("liq_rank") or 10**9) <= a.top]
    lines = ["# The deep scan: every setup instance in institutional names since 1995", "",
             f"Generated by `scripts/study/bank_v2/atlas_report.py` from `scan_history.py`, which read every stock's full daily "
             f"history in the bars database{f' ({a.scanned:,} stocks)' if a.scanned else ''}. {len(rows):,} instances in "
             f"{len({r['sym'] for r in rows}):,} stocks passed the owner's calibrated finders; {len(inst):,} of them, in "
             f"{len({r['sym'] for r in inst}):,} stocks, were in the top {a.top:,} stocks by 50-day dollar volume that session (the "
             "institutional cut used below). Stocks that have since delisted are not in the data, so the oldest eras lean toward "
             "the survivors.", "",
             "| setup | instances | clean | another setup fires too | worked (finder's test) | median culmination | low broke within 60 | distinct stocks |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    detail = []
    for sk, name in NAMES.items():
        mine = [r for r in inst if r["skill"] == sk]
        if not mine:
            continue
        clean = [r for r in mine if not r["co_fires"]]
        judged = [r for r in mine if r.get("works") is not None]
        worked = sum(1 for r in judged if r["works"])
        culm = [r["out"].get("culm_pct") for r in mine if (r.get("out") or {}).get("culm_pct") is not None]
        broke = sum(1 for r in mine if (r.get("out") or {}).get("broke_at") is not None)
        lines.append(f"| {name} | {len(mine)} | {len(clean)} | {len(mine) - len(clean)} | "
                     f"{pct(worked, len(judged)) if judged else 'no test'} | {statistics.median(culm):+.1f}% | {pct(broke, len(mine))} | "
                     f"{len({r['sym'] for r in mine})} |")
        co = Counter(c.split('.')[-1] for r in mine for c in r["co_fires"])
        detail += [f"## {name}", "",
                   f"- **by era:** " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(era(r['t']) for r in mine).items())),
                   f"- **by market** (SPY against its 50 and 200-day): " + ", ".join(f"{k} {v}" for k, v in Counter((r.get('ctx') or {}).get('market') or 'unknown' for r in mine).most_common()),
                   f"- **by sector:** " + ", ".join(f"{k} {v}" for k, v in Counter(r.get('sector') or 'unknown' for r in mine).most_common(11)),
                   f"- **fires on the same bar as:** " + (", ".join(f"{k} {v}" for k, v in co.most_common()) or "nothing"),
                   ""]
        if judged:
            by_mkt = Counter(); ok_mkt = Counter()
            for r in judged:
                m = (r.get("ctx") or {}).get("market") or "unknown"
                by_mkt[m] += 1; ok_mkt[m] += 1 if r["works"] else 0
            detail.insert(len(detail) - 1, "- **worked, by market:** " + ", ".join(f"{m} {pct(ok_mkt[m], by_mkt[m])} of {by_mkt[m]}" for m in by_mkt))
    lines += ["", "\"Worked\" is the finder's own test (the signal low not broken, at least an 8% move and up at +10 and +20 sessions; "
              "High Volume Edge and the Bear gap have none). \"Culmination\" is the best move before a close breaks the signal candle, "
              "within 60 sessions (the run-on's rule).", ""] + detail
    pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
