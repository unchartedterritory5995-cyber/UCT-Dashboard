"""Write the fixture that pins the JavaScript history source (index -> pieces -> joined, adjusted bars).

    python tools/history_lake/make_js_source_fixture.py

Output: app/src/data/historyLake/__fixtures__/source.json -- one SYNTHETIC symbol (seeded; no vendor
data: the repo is public) with a 5-minute series across three quarters and a 60-minute pair, its
index (with a split table) and the bars the Python reference returns for it, raw and adjusted.
``app/src/data/historyLake/source.test.js`` serves these pieces the way the edge does and must get
the same bars. Deterministic: running it twice writes the same file.
"""
from __future__ import annotations

import base64
import json
import random
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import factors  # noqa: E402
import piece  # noqa: E402

OUT = HERE.parents[1] / "app" / "src" / "data" / "historyLake" / "__fixtures__" / "source.json"
ET = ZoneInfo("America/New_York")
SYMBOL = "MU.LT"                       # a class-share spelling: the app asks for MU-LT
SPLITS = [["2026-06-29", 4.0], ["2026-10-05", 0.5]]


def _ts(day: str, hh: int, mm: int) -> int:
    y, m, d = (int(x) for x in day.split("-"))
    return int(datetime(y, m, d, hh, mm, tzinfo=ET).timestamp())


def _walk(rng, times, start):
    cols = {k: [] for k in piece.COLUMNS}
    px = start
    for t in times:
        o = px + rng.randint(-40, 40) * 100
        c = o + rng.randint(-40, 40) * 100
        cols["t"].append(t); cols["o"].append(o); cols["c"].append(c)
        cols["h"].append(max(o, c) + rng.randint(0, 20) * 100)
        cols["l"].append(min(o, c) - rng.randint(0, 20) * 100)
        cols["v"].append(rng.randint(1, 900_000) * 1_000_000)
        cols["n"].append(rng.randint(1, 4000))
        px = c
    return {k: np.asarray(v, dtype=np.int64) for k, v in cols.items()}


def build() -> dict:
    rng = random.Random(20261117)
    plan = [
        ("5", "2026Q2", [_ts(d, 9, 30) + 300 * i for d in ("2026-06-25", "2026-06-26", "2026-06-29", "2026-06-30") for i in range(20)]),
        ("5", "2026Q3", [_ts(d, 9, 30) + 300 * i for d in ("2026-07-01", "2026-09-30") for i in range(30)]),
        ("5", "2026Q4", [_ts(d, 9, 30) + 300 * i for d in ("2026-10-02", "2026-10-05", "2026-11-13") for i in range(25)]),
        ("60", "2026", [_ts(d, 9, 30) + 3600 * i for d in ("2026-06-26", "2026-06-29", "2026-10-05") for i in range(7)]),
        ("60e", "2026", [_ts(d, 4, 0) + 3600 * i for d in ("2026-06-26", "2026-06-29", "2026-10-05") for i in range(16)]),
    ]
    pieces, index, joined = [], {"v": piece.FORMAT_VERSION, "symbol": SYMBOL, "series": {}, "splits": SPLITS}, {}
    for series, period, times in plan:
        data = piece.encode_piece(SYMBOL, series, period, _walk(rng, times, 96_000_000), quality=5)
        dec = piece.decode_piece(data)
        hd = dec["header"]
        # one symbol per pack here, so each piece starts its pack (publish.py writes `off`)
        index["series"].setdefault(series, {})[period] = {
            "bars": hd["bars"], "bytes": len(data), "crc": hd["crc"], "first": hd["first"], "last": hd["last"], "off": 0}
        pieces.append({"relpath": piece.piece_relpath(series, SYMBOL, period), "series": series, "period": period,
                       "b64": base64.b64encode(data).decode("ascii")})
        fl = piece.bars_to_floats(dec)
        j = joined.setdefault(series, {k: [] for k in "tohlcvn"})
        j["t"] += [int(x) for x in dec["t"]]
        j["n"] += [int(x) for x in dec["n"]]
        for k in "ohlcv":
            j[k] += [float(x) for x in fl[k]]
    table = factors.build_factor_tables(
        [{"ticker": SYMBOL, "execution_date": d, "split_from": 1 if r >= 1 else int(round(1 / r)),
          "split_to": int(r) if r >= 1 else 1} for d, r in SPLITS], "2026-11-13")[SYMBOL]
    assert table == SPLITS
    expected = {}
    for series, j in joined.items():
        dates = [datetime.fromtimestamp(t, ET).date().isoformat() for t in j["t"]]
        ao, ah, al, ac, av = factors.adjust_bars(dates, j["o"], j["h"], j["l"], j["c"], j["v"], table)
        expected[series] = {"raw": j, "adjusted": {"o": ao, "h": ah, "l": al, "c": ac, "v": av}}
    return {"note": "Synthetic bars. Generated by tools/history_lake/make_js_source_fixture.py; do not edit.",
            "symbol": SYMBOL, "index_relpath": piece.index_relpath(SYMBOL), "index": index,
            "pieces": pieces, "expected": expected}


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(build(), sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n"
    tmp = OUT.with_suffix(".json.tmp")
    tmp.write_text(text, encoding="ascii", newline="\n")
    tmp.replace(OUT)
    print(f"wrote {OUT} ({len(text):,} bytes)")
