"""Write the fixture that pins the JavaScript piece reader to this encoder.

    python tools/history_lake/make_js_fixture.py

Output: app/src/data/historyLake/__fixtures__/pieces.json -- pieces built by ``piece.encode_piece``
from SYNTHETIC bars (seeded; no vendor data: the repo is public), each with the columns the Python
decoder returns. ``app/src/data/historyLake/piece.test.js`` decodes the same bytes and must agree.
Deterministic: running it twice writes the same file.
"""
from __future__ import annotations

import base64
import json
import random
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import piece  # noqa: E402

OUT = HERE.parents[1] / "app" / "src" / "data" / "historyLake" / "__fixtures__" / "pieces.json"
ET_STANDARD = timezone(timedelta(hours=-5))      # every fixture day is in November (EST)


def _ts(day: str, hh: int, mm: int) -> int:
    y, m, d = (int(x) for x in day.split("-"))
    return int(datetime(y, m, d, hh, mm, tzinfo=ET_STANDARD).timestamp())


def _walk(rng, times, start, tick, vol_scale, frac_every=0):
    """Integer bars at 1e6: a random walk on a ``tick`` grid, sometimes with a high below the
    body top (the format must hold it) and, when asked, fractional volume."""
    cols = {k: [] for k in piece.COLUMNS}
    px = start
    for i, t in enumerate(times):
        o = px + rng.randint(-40, 40) * tick
        c = o + rng.randint(-60, 60) * tick
        h = max(o, c) + rng.randint(0, 30) * tick
        low = min(o, c) - rng.randint(0, 30) * tick
        if i % 97 == 13:
            h = max(o, c) - tick          # vendor oddity: high below the body
        v = rng.randint(0, 250_000) * vol_scale
        if frac_every and i % frac_every == 0:
            v += rng.randint(1, vol_scale - 1)
        for k, x in zip(piece.COLUMNS, (t, max(o, tick), max(h, tick), max(low, tick), max(c, tick), v,
                                        rng.randint(0, 4000))):
            cols[k].append(x)
        px = max(c, 200 * tick)
    return {k: np.array(v, dtype=np.int64) for k, v in cols.items()}


def build():
    rng = random.Random(20261116)
    minutes = [_ts(d, 4, 0) + 60 * i for d in ("2026-11-09", "2026-11-10") for i in range(0, 960, 1)
               if rng.random() < 0.7]
    cases = []

    def add(name, symbol, series, period, bars, **kw):
        data = piece.encode_piece(symbol, series, period, bars, quality=5, **kw)
        dec = piece.decode_piece(data)
        ref = piece.decode_piece_reference(data)
        assert all((dec[k] == ref[k]).all() for k in piece.COLUMNS)
        fl = piece.bars_to_floats(dec)
        cases.append({
            "name": name, "symbol": symbol, "series": series, "period": period,
            "relpath": piece.piece_relpath(series, symbol, period),
            "b64": base64.b64encode(data).decode("ascii"),
            "header": dec["header"],
            "columns": {k: [int(x) for x in dec[k]] for k in piece.COLUMNS},
            "floats": {k: [float(x) for x in fl[k]] for k in "ohlcv"},
        })

    add("minute bars, 6-decimal prices, fractional volume", "ZZTEST", "1", "2026-11",
        _walk(rng, minutes, 412_345_600, 100, 1_000_000, frac_every=3))
    add("minute bars, cent prices, whole volume (scales collapse)", "BRK.B", "1", "2026-11",
        _walk(rng, minutes[:400], 512_340_000, 10_000, 1_000_000))
    add("lower-case class share, 5-minute", "BACpB", "5", "2026Q4",
        _walk(rng, [_ts("2026-11-09", 9, 30) + 300 * i for i in range(78)], 25_120_000, 10_000, 1_000_000))
    add("60-minute rth grid (half-hour unit)", "CON", "60", "2026",
        _walk(rng, [_ts("2026-11-09", 9, 30) + 3600 * i for i in range(7)], 88_000_000, 10_000, 1_000_000))
    add("60-minute eth grid", "ZZTEST", "60e", "2026",
        _walk(rng, [_ts("2026-11-09", 4, 0) + 3600 * i for i in range(16)], 3_141_500, 100, 1_000_000,
              frac_every=2))
    add("one bar", "X", "15", "2026",
        _walk(rng, [_ts("2026-11-09", 9, 30)], 1_000_000, 10_000, 1_000_000))
    big = _walk(rng, [_ts("2026-11-09", 9, 30) + 1800 * i for i in range(13)], 700_000_000_000, 1_000_000,
                1_000_000)
    big["v"] = big["v"] + 9_000_000_000_000_000 // 1_000_000 * 1_000_000 // 13     # volumes near 2**53
    big["n"][3] = 2 ** 53 - 1
    add("very large prices, volume and count (above 2**32)", "BIG", "30", "2026", big)
    return {"note": "Synthetic bars. Generated by tools/history_lake/make_js_fixture.py; do not edit.",
            "cases": cases}


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(build(), sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n"
    tmp = OUT.with_suffix(".json.tmp")
    tmp.write_text(text, encoding="ascii", newline="\n")
    tmp.replace(OUT)
    print(f"wrote {OUT} ({len(text):,} bytes)")
