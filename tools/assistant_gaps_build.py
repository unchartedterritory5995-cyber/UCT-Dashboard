"""Write docs/pine/assistant-writes-pine/GAPS.md from the engine's verdicts on the gap probes.

    python tools/assistant_gaps_build.py            # write it
    python tools/assistant_gaps_build.py --check    # change nothing; exit 1 if the file is stale

The verdicts themselves (`assistantGaps.json`) are regenerated by the browser lane:
    (cd app && WRITE_ASSISTANT_PINE_REFERENCE=1 node node_modules/vitest/vitest.mjs run \
       src/components/chart/supportLoop/assistantPineReference.test.js)
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import conftest  # noqa: E402,F401  side effect: every *_DB_PATH / *_DIR points at an isolated sandbox before `api` loads

from api.services import pine_authoring  # noqa: E402


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = pine_authoring.gaps_document()
    path = pine_authoring.GAPS_DOC
    current = path.read_text(encoding="utf-8").replace(chr(13) + chr(10), chr(10)) if path.exists() else ""
    if "--check" in argv:
        if current != text:
            print(f"STALE: {path} is not what the gap probes say now. Run: python tools/assistant_gaps_build.py")
            return 1
        print("ok: GAPS.md is current")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    with io.open(path, "w", encoding="utf-8", newline=chr(10)) as f:
        f.write(text)
    print(f"wrote {path}: {sum(1 for r in pine_authoring.gap_rows() if not r['served'])} gaps, "
          f"{sum(1 for r in pine_authoring.gap_rows() if r['served'])} probes served")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
