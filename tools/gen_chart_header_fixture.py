"""Make tools/fixtures/chart-header-nvda-1d.png, the screenshot the Tier 2 part A walk pastes.

A 900x500 PNG on a dark background whose top-left reads "NVDA · 1D · NASDAQ" in 18 px sans text,
the way a charting site headers a daily chart. The rest of the picture is a faint grid and a rising
candle-less line, so the image looks like a chart and OCR has the header to read and little else.
The walk step `smart.screenshot-tag` (tools/notebook_fin_walk_features.py) pastes it and waits for
"Tag NVDA · Daily".

Deterministic: no clock, no randomness, so the committed PNG can be regenerated byte for byte.

    python tools/gen_chart_header_fixture.py            # writes tools/fixtures/chart-header-nvda-1d.png
    python tools/gen_chart_header_fixture.py --check    # exits 1 if the committed file differs

The font is the repo's own DejaVu Sans (api/services/desk_assets), so the glyph shapes do not
depend on what is installed on the box that runs this.
"""
from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "tools" / "fixtures" / "chart-header-nvda-1d.png"
FONT = REPO / "api" / "services" / "desk_assets" / "DejaVuSans.ttf"

SIZE = (900, 500)
BACKGROUND = (13, 17, 23)
GRID = (32, 38, 47)
INK = (230, 233, 238)
LINE = (38, 166, 154)
HEADER = "NVDA · 1D · NASDAQ"
FONT_PX = 18


def render() -> bytes:
    img = Image.new("RGB", SIZE, BACKGROUND)
    draw = ImageDraw.Draw(img)
    w, h = SIZE
    for x in range(0, w, 100):
        draw.line([(x, 60), (x, h)], fill=GRID, width=1)
    for y in range(60, h, 80):
        draw.line([(0, y), (w, y)], fill=GRID, width=1)
    # A rising line with a few shallow pullbacks; fixed points, nothing random.
    pts = [(0, 430), (90, 410), (170, 420), (260, 360), (340, 372), (430, 300), (520, 318),
           (610, 240), (700, 252), (790, 170), (900, 150)]
    draw.line(pts, fill=LINE, width=3)
    font = ImageFont.truetype(str(FONT), FONT_PX)
    draw.text((16, 16), HEADER, font=font, fill=INK)
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=False)
    return buf.getvalue()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    args = ap.parse_args(argv)
    data = render()
    if args.check:
        have = OUT.read_bytes() if OUT.exists() else b""
        if have != data:
            print(f"DIFFERS: {OUT} ({len(have)} bytes on disk, {len(data)} generated)")
            return 1
        print(f"OK: {OUT} matches the generator ({len(data)} bytes)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(data)
    print(f"wrote {OUT} ({len(data)} bytes, {SIZE[0]}x{SIZE[1]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
