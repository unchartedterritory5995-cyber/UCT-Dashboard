"""U4 -- the CLOSED vocabulary of refusal guard codes the support loop may store.

`indicator_gap_hits` ranks what members hit by DISTINCT members per day. Phase A
stored only allowlisted built-in names; U4 adds the door's refusal GUARD CODES
(`pine:builtin`, `runtime:not-yet-graded`, `run-half:object-rail`, ...), so a
refusal that names no built-in is still a ranked work item.

⛔⛔ A CODE IS STORED ONLY WHEN IT IS ON THIS LIST, and this list is every guard-shaped
STRING LITERAL written in our own client source (`app/src`, tests excluded). A literal
in our source can never be member content, so the list is closed by construction: a
code the client sends that is not on it is counted as `_unlisted`, never written
verbatim. There is no guard registry in the engine (`ast/guardIdText.js`: ids are
literals across the lanes), so the list is DERIVED here, from the source, never typed.

    python tools/support_loop/refusal_codes.py --write     # regenerate the committed list
    python tools/support_loop/refusal_codes.py --check     # exit 1 when a literal is missing

The rail `tests/test_support_loop_refusal_codes.py` fails, by code, when the source
holds a guard literal the committed list lacks (regenerate with `--write`).

⛔ REGENERATING NEVER DELETES A CODE (2026-11-16). A code the list holds that the source no
longer writes is RETIRED, not dropped: it stays in `codes` (so the server still stores it by
name) and is recorded under `retired` with the date. A member's open tab on an older bundle
still sends it, and stored hits live 400 days; dropping it would turn a named work item into
`_unlisted` for no gain. A code is removed only by deleting its `retired` entry by hand.
"""
from __future__ import annotations

import datetime
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "app" / "src"
OUT = SRC / "components" / "chart" / "supportLoop" / "refusalCodes.json"
GUARD_ID_TEXT = SRC / "components" / "chart" / "engine" / "ast" / "guardIdText.js"

#: Namespaces the run-half / runtime lanes mint beyond `GUARD_NAMESPACES`
#: (`pine_runtime_telemetry.RUN_HALF_CODE_PATTERN`).
EXTRA_NAMESPACES = ("run-half", "pane", "interpret")
_ID = r"[A-Za-z0-9](?:[A-Za-z0-9._:-]{0,62}[A-Za-z0-9])?"
_SKIP_PARTS = ("__tests__", "__fixtures__", "__mocks__")


def namespaces() -> list[str]:
    """`GUARD_NAMESPACES` parsed out of `guardIdText.js` (the one list), plus the extras."""
    text = GUARD_ID_TEXT.read_text(encoding="utf-8")
    m = re.search(r"export const GUARD_NAMESPACES = Object\.freeze\(\[(.*?)\]\)", text, re.S)
    if not m:
        raise SystemExit("guardIdText.js no longer declares GUARD_NAMESPACES where this tool reads it")
    found = re.findall(r"'([a-z-]+)'", m.group(1))
    return sorted(set(found) | set(EXTRA_NAMESPACES))


def _is_test(p: Path) -> bool:
    n = p.name
    return (".test." in n or ".spec." in n or n.endswith(".measure.js")
            or any(part in _SKIP_PARTS for part in p.parts))


def scan(src: Path = SRC) -> list[str]:
    """Every quoted literal that is WHOLLY a guard code, in non-test .js/.jsx under `src`."""
    ns = "|".join(re.escape(n) for n in namespaces())
    rx = re.compile(r"""(['"`])((?:%s):%s)\1""" % (ns, _ID))
    codes: set[str] = set()
    for p in sorted(list(src.rglob("*.js")) + list(src.rglob("*.jsx"))):
        if _is_test(p) or "node_modules" in p.parts:
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for m in rx.finditer(text):
            code = m.group(2)
            if "${" in code:
                continue
            codes.add(code)
    return sorted(codes)


def document(codes: list[str], retired: dict | None = None) -> dict:
    return {
        "_comment": "GENERATED by tools/support_loop/refusal_codes.py --write. "
                    "The closed vocabulary of refusal guard codes api/services/indicator_support.py "
                    "may store in indicator_gap_hits (kind refusal-guard). Every entry is, or was, a "
                    "literal in our own client source, never member content. `codes` is every code "
                    "the server accepts: the live ones plus the keys of `retired`. `retired` holds "
                    "codes the source no longer writes; --write keeps them (an older open tab still "
                    "sends them, and stored hits live 400 days) and never deletes one. The only hand "
                    "edits: a retired entry's `stopped` note, and deleting a retired entry on purpose.",
        "version": 1,
        "codes": codes,
        "retired": retired or {},
    }


def _read(out: Path) -> dict:
    try:
        doc = json.loads(out.read_text(encoding="utf-8"))
        return doc if isinstance(doc, dict) else {}
    except (OSError, ValueError):
        return {}


def committed() -> list[str]:
    return list(_read(OUT).get("codes") or [])


def committed_retired() -> dict:
    r = _read(OUT).get("retired")
    return dict(r) if isinstance(r, dict) else {}


def regenerate(prior: dict, live: list[str], today: str) -> dict:
    """The next document. ⛔ NEVER LOSES A CODE: one on the prior list that the source no longer
    writes moves to `retired` (dated `today`) and stays in `codes`; an existing retired entry is
    kept as written (its hand-added `stopped` note included); a retired code the source writes
    again is live again. A code leaves only by deleting its retired entry by hand."""
    live_set = set(live)
    prior_retired = prior.get("retired") if isinstance(prior.get("retired"), dict) else {}
    retired = {c: v for c, v in prior_retired.items() if c not in live_set}
    for c in prior.get("codes") or []:
        if isinstance(c, str) and c not in live_set and c not in retired:
            retired[c] = {"since": today}
    retired = {c: retired[c] for c in sorted(retired)}
    return document(sorted(live_set | set(retired)), retired)


def write(out: Path = OUT, live: list[str] | None = None, today: str | None = None) -> dict:
    """Regenerate `out` in place from its own prior content and the live scan."""
    doc = regenerate(_read(out), scan() if live is None else live,
                     today or datetime.date.today().isoformat())
    out.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8", newline="\n")
    return doc


def main(argv: list[str]) -> int:
    if "--write" in argv:
        before = set(committed())
        doc = write()
        added = sorted(set(doc["codes"]) - before)
        print(f"wrote {len(doc['codes'])} codes ({len(added)} added, {len(doc['retired'])} retired, "
              f"0 removed) to {OUT.relative_to(ROOT)}")
        return 0
    codes = scan()
    listed = set(committed())
    missing = sorted(set(codes) - listed)
    if missing:
        print("refusal codes in the source but not in refusalCodes.json "
              "(run python tools/support_loop/refusal_codes.py --write):")
        for c in missing:
            print("  " + c)
        return 1
    orphaned = sorted(set(committed_retired()) - listed)
    if orphaned:
        print("retired codes that `codes` lacks, so the server would not accept them "
              "(run python tools/support_loop/refusal_codes.py --write):")
        for c in orphaned:
            print("  " + c)
        return 1
    print(f"ok: {len(codes)} live codes, {len(committed_retired())} retired")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
