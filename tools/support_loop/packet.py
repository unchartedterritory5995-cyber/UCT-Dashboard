# -*- coding: utf-8 -*-
"""The fix packet: one markdown brief an implementer agent can start from.

Sections, always in this order: the wall, the demand, the repro through the member
door, the affected scripts, the Pine reference, the suggested files, the parity
capture, the definition of done, and (for a report) the privacy note.

⛔ A REPORT'S PACKET QUOTES THE MEMBER'S REFUSED LINES and points at their source in
the work directory; it is written there and deleted with it. It must never be pasted
into a commit, a PR, an issue or a chat outside this machine.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

REPO = Path(__file__).resolve().parents[2]
AST = "app/src/components/chart/engine/ast"
HARNESS = REPO / "tests" / "fixtures" / "vendor" / "harness"

#: Where each capability is implemented. Paths are checked to exist when emitted.
FILES_BY_CAPABILITY = {
    "builtin-missing": [f"{AST}/pine.js", f"{AST}/closedTable.json", f"{AST}/interpret.js",
                        f"{AST}/callExpansions.js"],
    "call-mapping": [f"{AST}/pine.js", f"{AST}/callExpansions.js", f"{AST}/closedTable.json"],
    "drawing-objects": [f"{AST}/pineObjects.js", f"{AST}/objectProgram.js", f"{AST}/objectLoss.js",
                        "app/src/components/chart/engine/objectRuntime.js"],
    "collections": [f"{AST}/pine.js", f"{AST}/arrayVectors.js", f"{AST}/arrayWindows.js"],
    "request-security": [f"{AST}/pine.js", "app/src/components/chart/engine/mtfProjection.js",
                         "app/src/components/chart/engine/lowerTf.js"],
    "imports-libraries": [f"{AST}/pineLibraries.js", f"{AST}/pineLibraryStore.js"],
    "imperative": [f"{AST}/pine.js", f"{AST}/letPrepass.js", f"{AST}/interpret.js"],
    "user-functions": [f"{AST}/pine.js", f"{AST}/letPrepass.js"],
    "udt-methods": [f"{AST}/pine.js", f"{AST}/ufcs.js"],
    "history-offsets": [f"{AST}/pine.js", f"{AST}/barIndexShift.js"],
    "text-colour-values": [f"{AST}/pine.js", "app/src/components/chart/engine/colorInt.js",
                           "app/src/components/chart/engine/labelText.js"],
    "strategy": [f"{AST}/pine.js"],
}
ALWAYS = ["app/src/components/chart/supportLoop/doorNameCoverage.json (regenerate)",
          "app/src/components/chart/supportLoop/fixedGaps.json (call-unmapped fixes only)"]


def suggested_files(capability: Optional[str], name: Optional[str], *, limit: int = 6) -> list[str]:
    out = [p for p in FILES_BY_CAPABILITY.get(capability or "", [f"{AST}/pine.js"])
           if (REPO / p).exists()]
    # Engine files that already mention the bare name (e.g. `alma` for `ta.alma`):
    # often where a sibling is implemented. Tests excluded.
    if name:
        bare = name.split(".")[-1]
        if len(bare) >= 3:
            hits = []
            for p in (REPO / "app/src/components/chart/engine").rglob("*.js"):
                if ".test." in p.name or "__" in str(p.relative_to(REPO)):
                    continue
                try:
                    n = p.read_text(encoding="utf-8", errors="replace").count(bare)
                except OSError:
                    continue
                rel = p.relative_to(REPO).as_posix()
                if n and rel not in out:
                    hits.append((n, rel))
            out += [f"{rel} (mentions `{bare}` x{n})" for n, rel in sorted(hits, reverse=True)[:3]]
    return out[:limit + 3] + ALWAYS


def captures_using(name: Optional[str], *, limit: int = 8) -> list[str]:
    if not name or not HARNESS.exists():
        return []
    import re
    rx = re.compile(r"(?<![\w.])" + re.escape(name) + r"(?![\w])")
    out = []
    for p in sorted(HARNESS.glob("*.json")):
        try:
            src = ((json.loads(p.read_text(encoding="utf-8")).get("source") or {}).get("text")) or ""
        except (OSError, ValueError):
            continue
        if rx.search(src):
            out.append(p.stem)
    return out[:limit]


def _fence(text: str) -> str:
    return "```pine\n" + (text or "").rstrip("\n") + "\n```"


def render(*, title: str, kind: str, name: Optional[str], guard: Optional[str],
           capability: Optional[str], reference: Optional[str], demand: dict,
           repro: dict, sim: dict, master_sha: str, report: Optional[dict] = None,
           door_status: Optional[str] = None) -> str:
    L = [f"# Fix packet: {title}", ""]
    L.append(f"Generated by `tools/support_loop/triage.py` on build `{master_sha}`. "
             "Spec: `docs/pine/support-loop/PHASE-B.md`. "
             "This is fix-ready work, NOT a fix: it becomes a branch, is reviewed, and only then ships.")
    if report:
        L += ["", "> ⛔ **CONTAINS MEMBER SCRIPT CONTENT.** Kept only in the support-loop work "
              "directory and deleted when the report is closed. Never paste any of it into a commit, "
              "PR, issue, test fixture or chat. Write your own minimal repro for the fix."]
    L += ["", "## The wall", "",
          f"- **Built-in:** `{name}`" if name else "- **Built-in:** none (an unnamed construct)",
          f"- **Kind:** `{kind}`" + ("  (the door does not know the name)" if kind == "name-unknown"
                                     else "  (the door knows the name, and refuses this call or context)"),
          f"- **Door guard:** `{guard or '?'}` -> capability `{capability or '?'}`"]
    if door_status:
        L.append(f"- **Door-name probe on this build:** `{door_status}` (doorNameCoverage.json)")
    L += ["", "## Demand", ""]
    if demand.get("members") is not None:
        L.append(f"- {demand['members']} distinct member(s), {demand.get('hits', 0)} paste(s) in the last "
                 f"{demand.get('window_days', 30)} days (first {demand.get('first_day')}, last {demand.get('last_day')}).")
    if demand.get("reports"):
        L.append(f"- Open reports naming it: {', '.join('`' + r + '`' for r in demand['reports'])}")
    if report:
        L.append(f"- This report: `{report['id']}` ({report.get('status')}), {report.get('source_bytes')} bytes, "
                 f"{report.get('symbol') or '?'} {report.get('timeframe') or ''}, reported by "
                 f"{report.get('same_script_reports', 1)} report(s) of the same script; "
                 f"translator at report time `{report.get('translator_version')}`.")
    if not demand.get("members") and not demand.get("reports") and not report:
        L.append("- No member demand recorded in the window (triaged by name).")
    L += ["", "## Repro through the member door", "",
          "Asked exactly as the census asks (`coverageMapDoorCensus.measure.test.js`: "
          "`memberPaneDefinition` -> `installUserDefinitions`, objects-only pane armed, runtime pane dark, "
          "peeled up to the cap)."]
    for case in repro.get("cases") or []:
        L += ["", f"### {case['label']}", ""]
        if case.get("script") is not None:
            L.append(_fence(case["script"]))
        elif case.get("path"):
            L.append(f"Source: `{case['path']}`")
        L.append("")
        L.append(f"Verdict: attached={case.get('attached')} clean={case.get('clean')} "
                 f"stuck={case.get('stuck')!r}")
        for w in case.get("walls") or []:
            line = f"- `{w.get('guard')}` token `{w.get('token')}`"
            if w.get("line"):
                line += f" at line {w['line']}"
            if w.get("text"):
                line += f": `{w['text']}`"
            L.append(line)
            if w.get("message"):
                L.append(f"  - {w['message']}")
    L += ["", "## Affected scripts", "",
          f"Wall key `{sim.get('label')}` in `docs/pine/coverage-map.json`: blocks **{sim.get('blocked', 0)}** "
          f"sampled scripts; the ONLY wall of **{sim.get('sole', 0)}** (fixing it alone makes them transfer).",
          f"Census cache rows refused on this token but keyed elsewhere: {sim.get('census_token_hits', 0)}.",
          f"Corpus scripts that USE the name (using is not hitting): {sim.get('uses', 0)}."]
    for b in sim.get("blocked_sample") or []:
        sole = " **(sole wall)**" if b["walls"] == [sim.get("label")] else f" (walls: {', '.join(b['walls'][:4])})"
        L.append(f"- `{b['key']}` {b.get('title') or ''}{sole}")
    for u in (sim.get("uses_sample") or [])[:8]:
        L.append(f"- uses: `{Path(u['path']).name}` ({u['population']})")
    L += ["", "## Pine reference semantics", ""]
    L.append(f"- {reference}" if reference else "- (no single built-in: read the guard's refusal sentence above)")
    L.append("- Match TradingView's documented defaults, `na` handling and warm-up exactly; "
             "a number that differs from TradingView is a wrong answer, not an approximation.")
    L += ["", "## Suggested files", ""]
    L += [f"- `{f}`" if " (" not in f else f"- `{f.split(' (')[0]}` ({f.split(' (', 1)[1]}"
          for f in suggested_files(capability, name)]
    caps = captures_using(name)
    L += ["", "## Parity capture", ""]
    if caps:
        L.append(f"- Existing vendor captures whose source uses `{name}`: " + ", ".join(f"`{c}`" for c in caps)
                 + ". Re-run `vendorHarness.corpus.test.js` on them after the fix.")
    L.append("- Needed: a TradingView capture of the minimal repro (and of one sole-wall sample script if "
             "it is in `corpus/committed`) on `NYSE:RDDT` 1D and `AMEX:SPY` 1D, by "
             "`docs/pine/VENDOR-HARNESS.md` (`tools/vendor_harness/tv_capture.js`), into "
             "`tests/fixtures/vendor/harness/`. A door verdict is not a parity verdict.")
    L += ["", "## Definition of done", "",
          "1. On a new branch from origin/master: the repro above translates through the member door "
          "with zero refusals.",
          "2. A unit test pins the computed values (against TradingView's own numbers where a capture exists).",
          "3. `doorNameCoverage.json` regenerated "
          "(`WRITE_DOOR_NAME_COVERAGE=1 node node_modules/vitest/vitest.mjs run "
          "src/components/chart/supportLoop/doorNameCoverage.test.js` from `app/`).",
          "4. For a `call-unmapped` gap: an entry in `fixedGaps.json` with YOUR minimal repro "
          "(never member source), regenerated into the manifest as `fixed`.",
          "5. Reviewed, merged, deployed. Then: `python tools/support_loop/triage.py mark-fixed "
          + (f"--gap {name}`" if name else f"--report {report['id'] if report else '<id>'}`")
          + " (closes the linked reports and purges their work directories)."]
    return "\n".join(L) + "\n"
