# -*- coding: utf-8 -*-
"""demand_ranking.py - WHICH ENGINE UNIT UNLOCKS THE MOST-USED SCRIPTS: the parity roadmap, weighted by popularity.

`docs/pine/parity-roadmap.json` ranks each engine unit by HOW MANY sample scripts a fix of that unit alone would
let a member's chart serve (`sole`). A count treats a script nobody uses like one thousands of people have on
their charts. This file adds the second number: for each unit, the total of TradingView boosts (`agreeCount` in
`corpus/reference/*.json`) of the community scripts in its `soleScripts`. The two orders differ, and the
difference is the finding: on 2026-11-20 drawing objects led by boosts while strategies led by count.

    python tools/pine_coverage/demand_ranking.py build     # rewrite docs/pine/demand-ranking.json
    python tools/pine_coverage/demand_ranking.py check     # exit 1 when the committed file is not what build gives

HOW TO READ IT, AND WHAT IT DOES NOT SAY:
  * SOLE UNLOCKS ONLY. The roadmap lists scripts per unit only for `sole`. A unit that is one of two walls on a
    very popular script gets nothing here. TODO: an `any` column, when the roadmap lists scripts per unit for
    `any` (do not derive it from the census map: its per-script walls are not the roadmap's member walls).
  * BOOSTS ARE PUBLISHED POPULARITY, NOT OUR MEMBERS. Before launch there is no member demand to rank by (the
    admin gap ranking held a handful of rows, all from our own testing). When members' pastes exist in number,
    their counts belong beside this column, as aggregates.
  * BUILT-INS HAVE NO BOOST COUNT. They add to the script counts and nothing to the boosts.
  * PER UNIT, NOT PER UNIT OF WORK. `size` is the roadmap's own estimate; `soleBoostsPerSize` divides by it.

⛔ THE REPO IS PUBLIC: this file holds AGGREGATES PER UNIT ONLY (script counts and boost totals). No script
name, no source, no author, and nothing about a member. `tests/test_pine_demand_ranking.py` holds that.

DERIVED, like the roadmap: a rebuilt roadmap (or a re-fetched boost count) reds the test until this is rebuilt.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROADMAP = os.path.join(ROOT, "docs", "pine", "parity-roadmap.json")
CORPUS = os.path.join(ROOT, "corpus", "reference")
OUT = os.path.join(ROOT, "docs", "pine", "demand-ranking.json")
SCHEMA = "uct.pine-demand-ranking/v1"
#: the populations whose scripts carry a boost count (`<population>:<metadata file stem>` in the roadmap)
COMMUNITY = ("committed", "reference")
BUILTIN = "builtin"

HEADER = (
    "GENERATED by tools/pine_coverage/demand_ranking.py build. Do not edit by hand. Each engine unit of "
    "docs/pine/parity-roadmap.json with the scripts a fix of that unit ALONE would serve to a member (the roadmap's "
    "`sole`), and the total TradingView boosts (agreeCount, corpus/reference/*.json) of the community scripts among "
    "them. READ WITH CARE: sole unlocks only (a unit that is one of two walls on a popular script gets nothing "
    "here); boosts are published popularity, not our members' use; built-ins carry no boost count; ranked per unit, "
    "not per unit of work (see soleBoostsPerSize). Aggregates per unit only: no script name is in this file."
)


def boosts_of(corpus_dir: str = CORPUS) -> dict:
    """{metadata file stem: agreeCount} for every community script the corpus describes."""
    out = {}
    for name in sorted(os.listdir(corpus_dir)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(corpus_dir, name), encoding="utf-8") as f:
            meta = json.load(f)
        count = meta.get("agreeCount")
        out[name[:-5]] = int(count) if isinstance(count, (int, float)) and not isinstance(count, bool) and count >= 0 else 0
    return out


def build(roadmap: dict, boosts: dict) -> dict:
    """The ranking document. Pure: the same roadmap and boosts give the same bytes."""
    rows = []
    for u in roadmap["units"]:
        sole = list(u.get("soleScripts") or [])
        community = [s.split(":", 1)[1] for s in sole if s.split(":", 1)[0] in COMMUNITY and ":" in s]
        builtins = [s for s in sole if s.split(":", 1)[0] == BUILTIN]
        other = len(sole) - len(community) - len(builtins)
        total = sum(boosts.get(k, 0) for k in community)
        size = u.get("size") if isinstance(u.get("size"), int) and u.get("size") > 0 else 1
        rows.append({
            "unit": u["unit"], "kind": u.get("kind"), "size": u.get("size"),
            "soleScripts": len(sole), "soleCommunity": len(community), "soleBuiltins": len(builtins),
            # a script of a population this tool does not know, or one the corpus has no metadata for, is COUNTED
            # and SAID: it adds nothing to the boosts, and a silent zero would read as "nobody uses it"
            "soleOtherPopulation": other, "soleWithoutMetadata": sum(1 for k in community if k not in boosts),
            "soleBoosts": total, "soleBoostsPerSize": int(round(total / size)),
        })
    by_boosts = sorted(rows, key=lambda r: (-r["soleBoosts"], -r["soleScripts"], r["unit"]))
    by_count = sorted(rows, key=lambda r: (-r["soleScripts"], -r["soleBoosts"], r["unit"]))
    count_rank = {r["unit"]: i + 1 for i, r in enumerate(by_count)}
    for i, r in enumerate(by_boosts):
        r["rankByBoosts"] = i + 1
        r["rankByCount"] = count_rank[r["unit"]]
    head = roadmap.get("headline") or {}
    return {
        "schema": SCHEMA,
        "_comment": HEADER,
        "sample": {"scripts": head.get("sample"), "memberServed": head.get("memberServed"),
                   "communityScriptsWithABoostCount": len(boosts), "boostsInAll": sum(boosts.values())},
        "units": by_boosts,
    }


def text_of(doc: dict) -> str:
    return json.dumps(doc, indent=1, ensure_ascii=True) + "\n"


def load(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def check(roadmap_path: str = ROADMAP, corpus_dir: str = CORPUS, out_path: str = OUT) -> list:
    """The sections of the committed file that are not what `build` gives ([] when it is current)."""
    want = build(load(roadmap_path), boosts_of(corpus_dir))
    try:
        have = load(out_path)
    except (OSError, ValueError):
        return ["file"]
    return sorted(k for k in set(want) | set(have) if want.get(k) != have.get(k))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("build", "check"):
        p = sub.add_parser(name)
        p.add_argument("--roadmap", default=ROADMAP)
        p.add_argument("--corpus", default=CORPUS)
        p.add_argument("--out", default=OUT)
    a = ap.parse_args()
    if a.cmd == "check":
        bad = check(a.roadmap, a.corpus, a.out)
        print("demand-ranking.json is current" if not bad else f"demand-ranking.json is stale in: {', '.join(bad)}")
        return 1 if bad else 0
    doc = build(load(a.roadmap), boosts_of(a.corpus))
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text_of(doc))
    os.replace(tmp, a.out)
    for r in doc["units"]:
        if r["soleScripts"]:
            print(f"{r['rankByBoosts']:>3} {r['unit']:<26} sole {r['soleScripts']:>3} ({r['soleCommunity']}+{r['soleBuiltins']})"
                  f"  boosts {r['soleBoosts']:>9,}  by count {r['rankByCount']:>3}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
