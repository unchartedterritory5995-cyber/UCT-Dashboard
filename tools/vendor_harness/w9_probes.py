def all_files() -> dict:
    files = {f"w9-{sp['name']}.pine": build(sp) for sp in specs()}
    core = core_source()
    files["s1-broker-core.pine"] = core
    guarded, _ = range_guard.rewrite(core.replace("UCTPROBE_S1_BROKER", "UCTPROBE_S1_BROKER_RANGE", 1), RANGE_X_MS, RANGE_Y_MS)
