#!/usr/bin/env node
/*
 * emit_length_qualifiers.js  (W4-T8)
 *
 * Reads TradingView's Pine v6 reference (the JSON written by pine_reference_extract.js) and writes
 * the one fact the engine needs from it: for each function with a `length` parameter, the
 * qualifier that parameter is DECLARED with (`series int`, `simple int`, ...). The engine reads the
 * result (app/src/components/chart/engine/ast/windowLengthQualifiers.json); nothing is typed by hand.
 * Only function NAMES and a qualifier word are written; no reference text.
 *
 *   node tools/pine_survey/emit_length_qualifiers.js --ref <pine_v6_reference.json> [--check] [--out FILE]
 *   --check  compare against the committed file and exit 1 on any difference (writes nothing)
 */
const fs = require('fs')
const path = require('path')
const argv = process.argv.slice(2)
const arg = (f, d) => { const i = argv.indexOf(f); return i >= 0 && argv[i + 1] ? argv[i + 1] : d }
const REF = arg('--ref', null)
const REF5 = arg('--ref5', null)
const OUT = arg('--out', path.join(__dirname, '..', '..', 'app', 'src', 'components', 'chart', 'engine', 'ast', 'windowLengthQualifiers.json'))
if (!REF || !REF5) { console.error('--ref <v6 reference.json> and --ref5 <v5 reference.json> are required'); process.exit(2) }

/** The qualifier a parameter is declared with = the STRONGEST one it admits (`series` over `simple`...). */
const RANK = { series: 3, simple: 2, input: 1, const: 0 }
const declared = (ids) => {
  let best = null
  for (const id of ids || []) {
    const [q, ...t] = String(id).split(' ')
    if (!(q in RANK) || t.join(' ') !== 'int') continue
    if (best === null || RANK[q] > RANK[best]) best = q
  }
  return best === null ? null : `${best} int`
}

const lengthsOf = (file) => {
  const ref = JSON.parse(fs.readFileSync(file, 'utf8'))
  const lengths = {}
  for (const f of ref.functions || []) {
    const a = (f.args || []).find((x) => x && x.name === 'length')
    if (!a) continue
    const q = declared(a.allowedTypeIDs)
    if (q) lengths[f.name] = q
  }
  return Object.fromEntries(Object.keys(lengths).sort().map((k) => [k, lengths[k]]))
}
const sorted = lengthsOf(REF)
const sorted5 = lengthsOf(REF5)
const text = `${JSON.stringify({
  _: 'GENERATED by tools/pine_survey/emit_length_qualifiers.js from the Pine v6 reference. Do not hand-edit. `length` = the v6 reference, `v5Length` = the v5 reference: function -> declared qualifier of its `length` parameter (a version with no section, v4 and below, serves nothing).',
  length: sorted,
  v5Length: sorted5,
}, null, 2)}\n`
if (argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').split('\r\n').join('\n') : ''
  if (have !== text) { console.error('windowLengthQualifiers.json differs from the reference'); process.exit(1) }
  console.log(`ok: ${Object.keys(sorted).length} functions match`)
} else {
  fs.writeFileSync(OUT, text)
  console.log(`wrote ${Object.keys(sorted).length} functions to ${OUT}`)
}
