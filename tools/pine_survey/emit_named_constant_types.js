#!/usr/bin/env node
/*
 * emit_named_constant_types.js  (W34-I6b, item 4)
 *
 * Reads TradingView's Pine v6 reference (the JSON written by pine_reference_extract.js) and writes
 * the one fact the engine's v6 bool typing needs about Pine's NAMED CONSTANTS: the type each one is
 * DECLARED with, qualifier dropped (`const string` -> `string`). The engine reads the result
 * (app/src/components/chart/engine/ast/namedConstantTypes.json); nothing is typed by hand.
 * Only constant NAMES and a type word are written; no reference text.
 *
 * Scope: the families W34-I6b names (`size.*`, `text.align_*`, `xloc.*`, `yloc.*`, `extend.*`,
 * `label.style_*`, `line.style_*`). A constant of those families the reference types as anything
 * else (none today) is written with that type, so the engine never reads it as a string.
 *
 *   node tools/pine_survey/emit_named_constant_types.js --ref <pine_v6_reference.json> [--check] [--out FILE]
 *   --check  compare against the committed file and exit 1 on any difference (writes nothing)
 */
const fs = require('fs')
const path = require('path')
const argv = process.argv.slice(2)
const arg = (f, d) => { const i = argv.indexOf(f); return i >= 0 && argv[i + 1] ? argv[i + 1] : d }
const REF = arg('--ref', null)
const OUT = arg('--out', path.join(__dirname, '..', '..', 'app', 'src', 'components', 'chart', 'engine', 'ast', 'namedConstantTypes.json'))
if (!REF) { console.error('--ref <v6 reference.json> is required'); process.exit(2) }

const FAMILIES = ['size.', 'text.align_', 'xloc.', 'yloc.', 'extend.', 'label.style_', 'line.style_']
const QUALIFIERS = new Set(['const', 'input', 'simple', 'series'])

const ref = JSON.parse(fs.readFileSync(REF, 'utf8'))
const types = {}
for (const c of ref.constants || []) {
  const name = String((c && c.name) || '')
  if (!FAMILIES.some((p) => name.startsWith(p))) continue
  const words = String(c.type || '').trim().split(/\s+/)
  const ty = words.length === 2 && QUALIFIERS.has(words[0]) ? words[1] : null
  if (ty) types[name] = ty
}
const sorted = Object.fromEntries(Object.keys(types).sort().map((k) => [k, types[k]]))
const text = `${JSON.stringify({
  _: 'GENERATED by tools/pine_survey/emit_named_constant_types.js from the Pine v6 reference. Do not hand-edit. `type` = constant -> the type the reference declares it with, qualifier dropped. Families: size.*, text.align_*, xloc.*, yloc.*, extend.*, label.style_*, line.style_*.',
  families: FAMILIES,
  type: sorted,
}, null, 2)}\n`
if (argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').split('\r\n').join('\n') : ''
  if (have !== text) { console.error('namedConstantTypes.json differs from the reference'); process.exit(1) }
  console.log(`ok: ${Object.keys(sorted).length} constants match`)
} else {
  fs.writeFileSync(OUT, text)
  console.log(`wrote ${Object.keys(sorted).length} constants to ${OUT}`)
}
