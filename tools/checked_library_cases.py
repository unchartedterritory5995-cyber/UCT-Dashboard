"""THE SHARED CASES for "is this formula that library output?" (tests/fixtures/authoring/checked_library_cases.json).

ONE list of cases that both the door's rule (api/services/named_indicators.py) and the window's
port of it (app/src/components/chart/builder/authoring/checkedLibrary.js) are held to. Each case is
a recipe applied to an entry's output tree and what the result must be recognised as, BY
CONSTRUCTION (this generator knows what it did to the tree), never by running either implementation.
Deterministic: run it again and the file does not change.

    python tools/checked_library_cases.py            # write
    python tools/checked_library_cases.py --check    # change nothing; exit 1 if the file is stale

Run it after the library changes (a new entry, a new parameter, a moved range).
"""
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

doc = json.load(io.open(os.path.join(ROOT, "api/data/named_indicators.json"), encoding="utf-8"))


def node_at(tree, path):
    for i in path:
        tree = tree["args"][i]
    return tree


def another(p):
    """A different number the parameter can take."""
    step = 1 if p["integer"] else 0.5
    v = p["default"] + step
    if v <= p["max"]:
        return v
    if p["default"] - step >= p["min"]:
        return p["default"] - step
    # a range narrower than the step on both sides (a share between 0 and 1): halfway to its maximum
    return round((p["default"] + p["max"]) / 2, 6)


cases = []
for e in doc["indicators"]:
    params = {p["key"]: p for p in e["params"]}
    for o in e["outputs"]:
        here = [k for k in (p["key"] for p in e["params"]) if o["sites"].get(k)]     # the parameters this output uses
        base = {"entry": e["id"], "output": o["key"]}
        defaults = {k: params[k]["default"] for k in here}
        cases.append({**base, "kind": "defaults", "expect": defaults})
        cases.append({**base, "kind": "inside a larger formula", "wrap": True, "expect": None, "expect_inside": defaults})
        if here:
            moved = {k: another(params[k]) for k in here}
            cases.append({**base, "kind": "every parameter at another number", "set": moved, "expect": moved})
        for k in here:
            p = params[k]
            cases.append({**base, "kind": f"{k} under its minimum", "set": {k: p["min"] - (1 if p["integer"] else p["min"] / 2)}, "expect": None})
            cases.append({**base, "kind": f"{k} over its maximum", "set": {k: p["max"] + 1}, "expect": None})
            if p["integer"]:
                cases.append({**base, "kind": f"{k} not a whole number", "set": {k: p["default"] + 0.5}, "expect": None})
            sites = o["sites"][k]
            if len(sites) >= 2:
                cases.append({**base, "kind": f"{k} is one number in one place and another in the next",
                              "set_one": [k, 0, another(p)], "expect": None})
            if all(node_at(o["tree"], s)["type"] == "num" for s in sites):
                rest = {x: params[x]["default"] for x in here}
                rest[k] = None
                cases.append({**base, "kind": f"{k} driven by the member's own input", "series": k, "inputs": ["myOwnSetting"], "expect": rest})
                cases.append({**base, "kind": f"{k} is a series that is not a declared input", "series": k, "expect": None})
        # a number of the formula that is NOT a parameter, changed: a different indicator
        fixed = []
        taken = [s for ss in o["sites"].values() for s in ss]

        def walk(n, path):
            if isinstance(n, dict):
                if n.get("type") == "num" and list(path) not in taken:
                    fixed.append(list(path))
                for i, a in enumerate(n.get("args") or []):
                    walk(a, path + [i])
        walk(o["tree"], [])
        if fixed:
            cases.append({**base, "kind": "a number that is not a parameter was changed", "bump": [fixed[0], 7], "expect": None})

out = {"_": ("GENERATED by a helper from api/data/named_indicators.json. Each case is a RECIPE applied to that entry's output "
             "tree, in this order: `set` {parameter: number} writes the number at every place the parameter sits; `set_one` "
             "[parameter, n, number] writes it at the parameter's n-th place only; `series` parameter puts the series "
             "`myOwnSetting` at every place it sits; `bump` [path, d] adds d to the number at that path (a number that is not a "
             "parameter); `wrap` puts the whole tree as the first argument of `> 987654`. `inputs` are the member's declared "
             "inputs. `expect`: the parameters' numbers when the WHOLE tree is that output (null when it is not; a parameter "
             "driven by an input is null inside); `expect_inside`: the same, for the output found inside the larger formula. "
             "Held by tests/test_checked_library_parity.py (the door's rule) and checkedLibrary.test.js (the window's port)."),
       "cases": cases}
path = os.path.join(ROOT, "tests/fixtures/authoring/checked_library_cases.json")
text = json.dumps(out, ensure_ascii=False, separators=(",", ":")).replace('{"entry":', chr(10) + '{"entry":') + chr(10)
if "--check" in sys.argv[1:]:
    have = io.open(path, encoding="utf-8").read().replace(chr(13) + chr(10), chr(10)) if os.path.exists(path) else ""
    print("ok: the shared cases are current" if have == text else "STALE: run tools/checked_library_cases.py")
    sys.exit(0 if have == text else 1)
with io.open(path + ".tmp", "w", encoding="utf-8", newline=chr(10)) as fh:
    fh.write(text)
os.replace(path + ".tmp", path)
print(len(cases), "cases;", os.path.getsize(path), "bytes")
