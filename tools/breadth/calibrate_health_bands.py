"""Calibrate the Health score's per-universe bands (US / Nasdaq / NYSE) — run with the shading calibration.

Health (`breadth_monitor._score_breakdown`) maps five per-population readings through bands that
were set for UCT: % above the 50-day, the 5-day up/down ratio, the 13%/34-day up share, new highs
/ universe and the Stage 2 share. A broad universe (thousands of small caps) sits at different
levels, so UCT's bands would score it wrong. Each band edge is moved to the value at the SAME
percentile of the universe's own 2008+ history as UCT's edge holds in UCT's (the method the
put/call band was retuned with on 2026-11-19), so a reading earns the points that an equally
unusual reading earns on UCT. VIX, put/call and AAII are market-wide and keep their bands.

Reads the Monitor's own served UCT rows and each universe's stored rows (run where the breadth
store lives); writes api/services/breadth_health_bands.generated.json. Prints only percentiles.

    python tools/breadth/calibrate_health_bands.py
"""
from __future__ import annotations

import bisect
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "api", "services", "breadth_health_bands.generated.json")
FLOOR = "2008-01-02"


def pct_rank(vals: list, x: float) -> float:
    """Mid-rank percentile of x in ascending vals (ties count half)."""
    lo, hi = bisect.bisect_left(vals, x), bisect.bisect_right(vals, x)
    return (lo + hi) / 2 / len(vals)


def quantile(vals: list, q: float) -> float:
    pos = q * (len(vals) - 1)
    i = int(pos)
    j = min(i + 1, len(vals) - 1)
    return vals[i] + (vals[j] - vals[i]) * (pos - i)


def sig(x: float) -> float:
    return float(f"{x:.4g}")


def series(rows: list, key: str) -> list:
    from api.services import breadth_monitor as bm
    return sorted(v for r in rows if (v := bm.health_inputs(r)[key]) is not None)


def main() -> int:
    sys.path.insert(0, ROOT)
    from api.services import breadth_monitor as bm
    from api.services import breadth_shade_rule as rule
    from api.services import breadth_universe_monitor as bum
    uct = [r for r in bm.get_history_deep(8000)
           if not r.get("_live") and r.get("date", "") >= FLOOR and not rule.is_backtested_row(r, "uct")]
    doc = {"_doc": "GENERATED by tools/breadth/calibrate_health_bands.py -- the Health score's bands per "
                   "universe, each edge at the percentile UCT's edge holds in UCT's own history.",
           "uct_from": uct[-1]["date"], "uct_to": uct[0]["date"], "uct_sessions": len(uct)}
    for u in bum.UNIVERSES:
        ds = [d for d in bum.dates(u) if d >= FLOOR]
        by = bum.rows_for_dates(u, ds)
        rows = [by[d] for d in ds if d in by]
        bands, said = {}, []
        for key, (lo, hi) in bm.UCT_BANDS.items():
            a, b = series(uct, key), series(rows, key)
            if len(a) < 250 or len(b) < 250:
                raise SystemExit(f"{u} {key}: too little history ({len(a)} / {len(b)})")
            plo, phi = pct_rank(a, lo), pct_rank(a, hi)
            bands[key] = [sig(quantile(b, plo)), sig(quantile(b, phi))]
            said.append(f"{key} p{plo * 100:.0f}-p{phi * 100:.0f}")
        doc[u] = {"sessions": len(rows), "bands": bands}
        print(f"{u}: {len(rows)} sessions; edges at " + ", ".join(said))
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
