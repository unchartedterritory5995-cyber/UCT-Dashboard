"""Tabulate sandbox/<label>/probe.json for lane R1b's four boots -> sandbox-results.md (mechanical)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABELS = ["s00-tip", "s-L2", "s-L1a", "s-wave7"]


def door(d):
    if "json" in d:
        return f"{d['status']} {'JSON' if d['json'] else d.get('content_type') or 'non-JSON'}"
    return str(d.get("status"))


rows = []
for lab in LABELS:
    p = json.loads((HERE / "sandbox" / lab / "probe.json").read_text(encoding="utf-8"))
    integ = (HERE / "sandbox" / lab / "sandbox-integrity.txt").read_text(encoding="utf-8").split(" -- ")[0]
    L, R, E = p["landings"], p["r1b_doors"], p["editor"]
    ed = "; ".join(f"{k}: PUT {','.join(x['schema'] or '-' for x in v.get('body_puts', []))} -> "
                   f"{','.join(map(str, v.get('put_statuses', [])))}, marker {'kept' if v.get('stored_keeps_marker') else 'LOST'}, "
                   f"typed {'saved' if v.get('stored_has_typed') else 'not saved'}, errors {len(v.get('page_errors', []))}"
                   for k, v in E.items())
    rows.append((lab, integ.replace("SANDBOX INTEGRITY: ", ""), p["proven"],
                 p["L2_editor_header"].get("more_note_actions_buttons"),
                 L["L1c_switcher_body_recall"]["text_matches"], door(L["L1b_admin_notebook_slo"]),
                 door(L["L1a_unbuildable_body_at_create"]), door(L["h203_depth_cap_at_create"]),
                 f"{R['L1a_writing_help_autofill']['status']} {R['L1a_writing_help_autofill']['content_type']}",
                 f"{R['w7_writing_help_stream']['status']} {R['w7_writing_help_stream']['content_type']}",
                 door(L["w7_personal_tokens"]), door(R["kept_TERM078_ai_meters"]), door(L["w6_note_templates"]), ed))
head = ("step", "integrity", "identity proven", "L2 More-menu buttons", "L1c body recall", "L1b SLO door",
        "L1a empty-text create", "#203 depth cap", "L1a autofill POST", "w7 writing-help stream POST",
        "w7 personal tokens", "kept TERM-078 meters", "w6 templates", "never-revert notes (n2/n1/n0)")
out = ["# Lane R1b sandbox results (generated by results.py from sandbox/*/probe.json)", "",
       "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
(HERE / "sandbox-results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
for lab in LABELS:
    p = json.loads((HERE / "sandbox" / lab / "probe.json").read_text(encoding="utf-8"))
    print(lab, "autofill:", p["r1b_doors"]["L1a_writing_help_autofill"], "stream:", p["r1b_doors"]["w7_writing_help_stream"],
          "meters:", p["r1b_doors"]["kept_TERM078_ai_meters"], "dom:", {k: p["dom"].get(k) for k in ("skip_link", "pane_heading")},
          "L2 errs:", p["L2_editor_header"].get("page_errors"))
