"""The multi-state recurrence (``accum2``/``accum3``/``accum4``) in the Python lane,
held to the JS lane's own output.

⛔ THE FIXTURE IS THE ONE AUTHORITY. ``app/.../multiState.test.js`` writes and reads
``tests/fixtures/ast/multi_state_parity.json``; this file holds THIS lane to it at
1e-9, so a lane that drifts fails against the other lane's output rather than a
number retyped here. The JS file also compares itself to an independent plain-loop
reference, so the fixture is not two lanes agreeing on a shared mistake.
"""
from __future__ import annotations

import io
import json
import math
import pathlib

import pytest

from api.services import ast_interpret as ai
from api.services.ast_table import multi_states, recurrence_bindings

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "ast" / "multi_state_parity.json"


def _doc() -> dict:
    return json.load(io.open(FIXTURE, encoding="utf-8"))


def _bars() -> list:
    out = []
    for b in _doc()["bars"]:
        out.append({"t": b["t"], "o": b["o"], "h": b["h"], "l": b["l"],
                    "c": math.nan if b["c"] is None else b["c"], "v": b["v"]})
    return out


def _col(tree, bars=None):
    got = ai.interpret(tree, bars if bars is not None else _bars(), {})
    return [None if (v is None or (isinstance(v, float) and not math.isfinite(v))) else v for v in got]


@pytest.mark.parametrize("k", range(5))
def test_each_case_matches_the_other_lane_bar_for_bar(k):
    case = _doc()["cases"][k]
    got = _col(case["ast"])
    expected = case["expected"]
    assert len(got) == len(expected)
    for i, (a, b) in enumerate(zip(got, expected)):
        if b is None:
            assert a is None, f"{case['source']} bar {i}: this lane produced {a} where the other produced nothing"
            continue
        assert a is not None, f"{case['source']} bar {i}: this lane produced nothing where the other produced {b}"
        assert abs(a - b) < 1e-9, f"{case['source']} bar {i}: {a} vs {b}"


def test_the_fixture_is_not_mostly_holes():
    # ⛔ NON-VACUITY. The comparison above passes on an all-null column.
    for case in _doc()["cases"]:
        assert sum(1 for v in case["expected"] if v is not None) > 100


def test_the_declaration_is_read_off_the_manifest():
    ms = multi_states()
    assert sorted(ms) == ["accum2", "accum3", "accum4"]
    for name, spec in ms.items():
        assert len(spec["seeds"]) == len(spec["updates"]) == len(spec["binds"])
    for b in ("state1", "state2", "state3", "state4"):
        assert b in recurrence_bindings()


def test_the_two_outputs_differ_so_output_is_really_read():
    """⛔ A lane that ignored ``output`` would pass cases 0 and 1 only if the
    fixture were generated by the same bug; within THIS lane they must differ."""
    cases = _doc()["cases"]
    a, b = _col(cases[0]["ast"]), _col(cases[1]["ast"])
    assert any(x is not None and y is not None and abs(x - y) > 1e-6 for x, y in zip(a, b))


def _call(name, *args):
    return {"type": "call", "name": name, "args": list(args)}


def _num(v):
    return {"type": "num", "value": v}


def _s(name):
    return {"type": "series", "name": name}


def _op(name, *args):
    return {"type": "op", "name": name, "args": list(args)}


def _refused(tree, guard, bars=None):
    with pytest.raises(Exception) as err:
        ai.interpret(tree, bars if bars is not None else _bars()[:40], {})
    assert getattr(err.value, "guard", None) == guard, str(err.value)


def test_a_bind_in_a_seed_is_refused():
    _refused(_call("accum2", _num(1), _num(5), _s("state1"), _num(0), _num(1), _num(2)), "interpret:recurrence")


def test_a_bind_under_an_offset_is_refused():
    off = {"type": "offset", "value": 1, "args": [_s("state1")]}
    _refused(_call("accum2", _num(1), _num(5), _s("close"), _num(0), off, _num(2)), "interpret:recurrence")


def test_a_bind_under_a_windowed_call_is_refused():
    _refused(_call("accum2", _num(1), _num(5), _s("close"), _num(0),
                   _call("sma", _s("state1"), _num(3)), _num(2)), "interpret:recurrence")


def test_a_bind_outside_any_update_is_refused():
    _refused(_op("+", _s("state1"), _num(1)), "interpret:recurrence")


def test_an_output_past_k_is_refused():
    _refused(_call("accum2", _num(3), _num(5), _num(0), _num(1), _s("state2"), _s("state1")), "resolve:window")


def test_fibonacci_steps_both_states_together():
    got = ai.interpret(_call("accum2", _num(2), _num(5), _num(0), _num(1), _s("state2"),
                             _op("+", _s("state1"), _s("state2"))), _bars()[:30], {})
    assert all(v is None for v in got[:5])  # this lane answers not-computable as None
    assert all(v == 8 for v in got[5:])
