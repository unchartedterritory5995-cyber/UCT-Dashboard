"""UCT Agent program, agent-qa: COST BASELINE — model calls per corpus phrasing, today (Sprint 2 task 3).

A MEASUREMENT, pinned exactly so a reduction (or a regression) shows up as a reviewed diff. No paid call: the
server is driven with a scripted model; research is stubbed.

Per phrasing:
  browser_requests  /api/agent/turn requests the REAL panel makes (0 = the no-model fast path handled it),
                    from app/src/agent/__fixtures__/program/scores/fastpath-candidates.json (fastPathCorpus.test.jsx)
  server_calls      model calls `turn.run_turn` makes for ONE request with a scripted planner that answers directly
                    (1; 2 when UCT forces research for current-facts wording, which adds the post-research call)
  research_calls    web research calls in that request
  naming_call       1 when the request leaves a new conversation unnamed (the plan gave no title: router
                    `_name_unnamed`), else 0. Measured as the upper bound: the scripted plan gives no title.
  model_calls       browser_requests × (server_calls + naming_call)  ← the number to reduce

Regenerate after a REVIEWED change:
    C:\\UCT\\agent\\.venv\\Scripts\\python.exe -m tests.test_uct_agent_qa_cost_baseline --write
"""
from __future__ import annotations

import json
import sys
import types
from pathlib import Path

import pytest

from api.services.uct_agent import turn

REPO = Path(__file__).resolve().parents[1]
SCORES = REPO / "app" / "src" / "agent" / "__fixtures__" / "program" / "scores"
FASTPATH = SCORES / "fastpath-candidates.json"
BASELINE = SCORES / "cost-baseline.json"
CORPORA = {"discovery": REPO / "api" / "services" / "uct_agent" / "scan" / "eval" / "discovery.json"}

_ANSWER = ('{"disposition":"answer","reply":"ok","question":null,"ops":[],"unsupported_category":null,'
           '"research":null,"title":null}')


def _scripted(calls):
    def call(**kw):
        calls.append(kw)
        return types.SimpleNamespace(content=[types.SimpleNamespace(type="text", text=_ANSWER)], stop_reason="end_turn",
                                     usage=types.SimpleNamespace(input_tokens=1, output_tokens=1))
    return call


def server_cost(message: str, monkeypatch) -> dict:
    """One request through the REAL run_turn: how many model calls and research calls it makes."""
    research = []
    monkeypatch.setattr(turn, "_record_cost", lambda resp: 0.0)
    monkeypatch.setattr(turn, "_research", lambda q, r: research.append(q) or {"results": [], "query": q})
    calls = []
    out = turn.run_turn(message=message, context={}, history=[], caller=_scripted(calls))
    assert calls, "no model call: the measurement would be vacuous"
    named = 0 if (out.get("title") or (out.get("envelope") or {}).get("title")) else 1
    return {"server_calls": len(calls), "research_calls": len(research), "naming_call": named,
            "usage_model_calls": (out.get("usage") or {}).get("model_calls")}


def measure(monkeypatch) -> dict:
    fp = json.loads(FASTPATH.read_text(encoding="utf-8"))["questions"]
    out = {"about": "generated by tests/test_uct_agent_qa_cost_baseline.py — a measurement, do not edit by hand",
           "model": "scripted planner (answers directly), research stubbed, naming as upper bound", "corpora": {}}
    for name, path in CORPORA.items():
        corpus = json.loads(path.read_text(encoding="utf-8"))
        rows, totals = {}, {"phrasings": 0, "browser_requests": 0, "model_calls": 0, "research_calls": 0,
                            "fast_path_zero_call": 0}
        by_cat: dict[str, dict] = {}
        for q in corpus["questions"]:
            got = fp.get(q["id"])
            assert got is not None, f"{q['id']}: not measured by fastPathCorpus.test.jsx"
            br = int(got["model_turns"])
            s = server_cost(q["question"], monkeypatch) if br else {"server_calls": 0, "research_calls": 0,
                                                                    "naming_call": 0, "usage_model_calls": 0}
            assert s["usage_model_calls"] in (None, s["server_calls"]), (q["id"], s)  # run_turn's own count agrees
            mc = br * (s["server_calls"] + s["naming_call"])
            rows[q["id"]] = {"browser_requests": br, "server_calls": s["server_calls"],
                             "research_calls": br * s["research_calls"], "naming_call": s["naming_call"],
                             "model_calls": mc}
            c = by_cat.setdefault(q.get("category", "?"), {"phrasings": 0, "model_calls": 0})
            c["phrasings"] += 1
            c["model_calls"] += mc
            totals["phrasings"] += 1
            totals["browser_requests"] += br
            totals["model_calls"] += mc
            totals["research_calls"] += br * s["research_calls"]
            totals["fast_path_zero_call"] += int(br == 0)
        out["corpora"][name] = {"version": corpus.get("version"), "totals": totals,
                                "by_category": dict(sorted(by_cat.items())), "phrasings": rows}
    return out


def baseline_text(monkeypatch) -> str:
    return json.dumps(measure(monkeypatch), indent=1, sort_keys=True) + "\n"


# ── rails ────────────────────────────────────────────────────────────────────────────────────────────────
def test_the_scripted_server_counts_one_call_for_a_plain_question_and_two_with_forced_research(monkeypatch):
    """CONTROL: the instrument can tell the cases apart (otherwise every phrasing would read the same)."""
    assert server_cost("show me stocks with RS rank above 80", monkeypatch)["server_calls"] == 1
    forced = server_cost("what is the latest news on NVDA", monkeypatch)
    assert forced["server_calls"] == 2 and forced["research_calls"] == 1, forced


def test_the_cost_baseline_matches_the_recorded_one_exactly(monkeypatch):
    want = baseline_text(monkeypatch)
    assert BASELINE.exists(), "generate it: python -m tests.test_uct_agent_qa_cost_baseline --write"
    have = BASELINE.read_text(encoding="utf-8").replace("\r\n", "\n")
    assert have == want, "the cost baseline moved; review it, then --write"


def test_every_corpus_phrasing_is_measured_and_none_exceeds_the_per_request_ceiling(monkeypatch):
    m = measure(monkeypatch)
    for name, c in m["corpora"].items():
        assert c["totals"]["phrasings"] >= 1, name
        for qid, r in c["phrasings"].items():
            assert r["server_calls"] <= turn.MAX_RESEARCH_CALLS + 1, (qid, r)        # the 2-call ceiling
            assert r["research_calls"] <= r["browser_requests"] * turn.MAX_RESEARCH_CALLS, (qid, r)


if __name__ == "__main__":
    if "--write" in sys.argv:
        mp = pytest.MonkeyPatch()
        try:
            text = baseline_text(mp)
        finally:
            mp.undo()
        with open(BASELINE, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(BASELINE)
        print(json.dumps({k: v["totals"] for k, v in json.loads(text)["corpora"].items()}, indent=1))
