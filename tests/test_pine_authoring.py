"""THE ASSISTANT WRITES PINE: its instructions list ONLY what the engine serves (2026-11-18).

`api/services/pine_authoring.py` writes the assistant's instructions for a script from
`assistantPineReference.json`, which the browser lane GENERATES from the engine's own tables and
verdicts (`app/src/components/chart/supportLoop/assistantPineReference.test.js` regenerates it and
fails when the committed bytes differ). This file holds the server half:

  * the document prints nothing the reference does not serve: an output whose probe did not run, a
    worked example that did not run, a drawing family that is not admitted are all absent;
  * a pitfall's warning is printed only while the engine still does not draw it;
  * every admitted capability is worded, and no words exist for an id the detector cannot return;
  * a worked example the RUNTIME lane draws uses only capabilities the server admits today (the
    browser's generator runs the engine; admission is the server's, so it is checked here);
  * with no readable reference there is no document, and nothing may make a script turn.
"""
from __future__ import annotations

import copy
import pathlib
import re

import pytest

from api.services import pine_authoring as pa
from api.services import pine_capabilities
from api.services import runtime_definitions

ROOT = pathlib.Path(__file__).resolve().parents[1]
REF = pa.reference()
GENERATOR = (ROOT / "app" / "src" / "components" / "chart" / "supportLoop" / "assistantPineReference.js").read_text(encoding="utf-8")


def section(doc, title):
    """The lines under one `## title` heading."""
    lines = doc.split("\n")
    at = next(i for i, l in enumerate(lines) if l.startswith("## ") and l[3:].startswith(title))
    end = next((i for i in range(at + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return "\n".join(lines[at + 1:end])


# ═══ 1. the reference ════════════════════════════════════════════════════

def test_the_reference_is_readable_and_is_the_generators():
    assert REF and REF["version"] == 1 and pa.available()
    assert REF["_comment"].startswith("GENERATED by app/src/components/chart/supportLoop/assistantPineReference.test.js")
    # the states that mean "runs" are the generator's own
    (js,) = re.findall(r"export const RUNS_STATES = Object\.freeze\(\[([^\]]+)\]\)", GENERATOR)
    assert tuple(re.findall(r"'([^']+)'", js)) == pa.RUNS_STATES


def test_every_worked_example_ran_and_a_runtime_one_is_admitted_by_the_server_today():
    admitted = set(runtime_definitions.admitted_capabilities()["admitted"])
    assert set(REF["admitted"]) == admitted, "the reference was generated from another admission table"
    examples = pa.worked_examples()
    assert len(examples) == len(REF["examples"]) >= 10
    lanes = set()
    for e in examples:
        assert pa.script_problem(e["source"]) is None, e["id"]
        lanes.add(e["lane"])
        if e["lane"] == "runtime":
            missing = set(pine_capabilities.capabilities_of(e["source"])) - admitted
            assert not missing, (e["id"], sorted(missing))
    assert lanes == {"host", "runtime"}                                    # both lanes are shown


def test_CONTROL_admission_can_refuse_an_example_shaped_script():
    """The check above can fail: a script that uses a capability the server does not admit."""
    admitted = set(runtime_definitions.admitted_capabilities()["admitted"])
    script = "//@version=5\nindicator('x')\nvarip float n = 0.0\nn += 1\nplot(n, 'n')\n"
    assert "varip" in set(pine_capabilities.capabilities_of(script)) - admitted


# ═══ 2. the document prints only what is served ══════════════════════════

def test_the_document_is_built_and_is_the_same_every_time():
    doc = pa.document()
    assert doc == pa.document() and doc.endswith("\n")
    assert 8_000 < len(doc) < 40_000
    assert doc.startswith("You write ONE complete Pine Script indicator")
    for heading in ("LANGUAGE YOU MAY USE", "WHAT A SCRIPT CAN SHOW", "VALUE FUNCTIONS AND VARIABLES", "DRAWING: TABLE",
                    "DRAWING: LINE", "DRAWING: LABEL", "DRAWING: BOX", "DRAWING CONSTANTS", "LIMITS", "TEXT", "ARRAYS",
                    "COLOURS", "NEVER", "WORKED EXAMPLES"):
        assert f"## {heading}" in doc, heading
    assert "`table.new(" in doc and "`ta.sma`" in doc and "```pine" in doc


def test_an_output_is_listed_only_when_its_own_probe_ran():
    served = pa.served_outputs()
    assert {"plot", "plotshape", "bgcolor", "barcolor", "fill"} <= set(served)
    shown = section(pa.document(), "WHAT A SCRIPT CAN SHOW")
    assert re.findall(r"`([a-z]+)`", shown) == served
    withheld = [o["name"] for o in REF["outputs"] if o["name"] not in served]
    assert "hline" in withheld                                             # today: asked, and not drawn
    for name in withheld:
        assert f"`{name}`" not in shown
    # take one away in the reference and it leaves the document
    ref = copy.deepcopy(REF)
    next(o for o in ref["outputs"] if o["name"] == "fill")["state"] = "not-yet"
    assert "`fill`" not in section(pa.document(ref), "WHAT A SCRIPT CAN SHOW")


def test_an_example_that_did_not_run_is_never_shown():
    ref = copy.deepcopy(REF)
    dropped = ref["examples"][0]
    dropped["ok"] = False
    doc = pa.document(ref)
    assert dropped["title"] not in doc and ref["examples"][1]["title"] in doc
    withheld = copy.deepcopy(REF)
    withheld["examples"][0]["state"] = "runs-withheld"
    assert withheld["examples"][0]["title"] not in pa.document(withheld)


def test_a_drawing_family_is_printed_only_when_the_reference_admits_it():
    doc = pa.document()
    drawn = set(re.findall(r"`((?:line|label|box|table|linefill|polyline)\.[a-z_0-9]+)\(", doc))
    listed = {op["name"] for fam in REF["families"] for op in REF["drawing"][fam]}
    assert drawn <= listed | {"line.new", "label.new", "box.new", "table.new", "table.cell", "line.delete", "box.delete"}
    assert not any(n.startswith(("linefill.", "polyline.")) for n in drawn)
    ref = copy.deepcopy(REF)
    ref["families"] = [f for f in ref["families"] if f != "table"]
    assert "## DRAWING: TABLE" not in pa.document(ref)
    for banned in ("matrix.", "map.new", "linefill.", "polyline.", "strategy.entry", "request.earnings", "request.financial"):
        assert banned not in doc, banned


def test_a_pitfall_is_warned_about_only_while_it_stands():
    assert set(pa.standing_pitfalls()) <= set(pa.PITFALL_WORDS), "a standing pitfall has no sentence"
    never = section(pa.document(), "NEVER")
    for pid in pa.standing_pitfalls():
        assert pa.PITFALL_WORDS[pid] in never
    ref = copy.deepcopy(REF)
    for p in ref["pitfalls"]:
        p["standing"] = False
    cleared = section(pa.document(ref), "NEVER")
    for sentence in pa.PITFALL_WORDS.values():
        assert sentence not in cleared
    # every pitfall sentence belongs to a pitfall the generator asks the engine about
    probes = set(re.findall(r"^  '?([a-z-]+)'?: '//@version", GENERATOR, re.M))
    assert set(pa.PITFALL_WORDS) == probes == {p["id"] for p in REF["pitfalls"]}


def test_every_admitted_capability_is_worded_and_no_other_is_printed():
    # every admitted capability is either worded for the assistant or NAMED as deliberately not offered
    spoken_for = set(pa.CAPABILITY_WORDS) | set(pa.NOT_FOR_THE_ASSISTANT)
    assert set(REF["admitted"]) <= spoken_for, sorted(set(REF["admitted"]) - spoken_for)
    assert not (set(pa.CAPABILITY_WORDS) & set(pa.NOT_FOR_THE_ASSISTANT))
    assert set(pa.CAPABILITY_WORDS) | set(pa.NOT_FOR_THE_ASSISTANT) <= set(pine_capabilities.CAPABILITY_IDS),         "words for an id the detector cannot return"
    assert all(reason for reason in pa.NOT_FOR_THE_ASSISTANT.values())
    assert "strategy" not in section(pa.document(), "LANGUAGE YOU MAY USE")
    language = section(pa.document(), "LANGUAGE YOU MAY USE")
    for cap in REF["admitted"]:
        if cap not in pa.NOT_FOR_THE_ASSISTANT:
            assert pa.CAPABILITY_WORDS[cap] in language
    ref = copy.deepcopy(REF)
    ref["admitted"] = [c for c in ref["admitted"] if c != "while"]
    assert pa.CAPABILITY_WORDS["while"] not in pa.document(ref)


def test_names_the_engine_refuses_are_only_ever_under_never():
    doc = pa.document()
    never = section(doc, "NEVER")
    for name in REF["refusedNames"]:
        assert f"`{name}` is refused by name" in never
        assert doc.count(f"`{name}`") == 1, name


# ═══ 3. fail closed ══════════════════════════════════════════════════════

@pytest.mark.parametrize("broken", [
    {}, {"version": 1}, {"version": 1, "admitted": ["core"], "outputs": [], "examples": []},
])
def test_with_no_usable_reference_there_is_no_document(broken):
    assert pa.available(broken) is False
    with pytest.raises(ValueError):
        pa.document(broken)


def test_an_unreadable_file_is_no_reference(monkeypatch, tmp_path):
    bad = tmp_path / "assistantPineReference.json"
    bad.write_text("{not json", encoding="utf-8")
    monkeypatch.setattr(pa, "REFERENCE_PATH", bad)
    pa.reference.cache_clear()
    try:
        assert pa.reference() == {} and pa.available() is False
    finally:
        pa.reference.cache_clear()


# ═══ 4. the server's first look at a script ══════════════════════════════

#: A script that declares a library. Written in two pieces: the repository's own rail forbids any file
#: from holding that declaration as one literal (`tests/test_pine_library_pinning.py`).
LIBRARY_SCRIPT = "//@version=5" + chr(10) + "lib" + "rary('x')" + chr(10)
OK_SCRIPT = "//@version=5\nindicator(\"x\", overlay=true)\nplot(close, \"Close\")\n"


@pytest.mark.parametrize("pine,why", [
    (None, "no script was written"), ("   ", "no script was written"),
    ("//@version=6\nindicator('x')\nplot(close, 'c')\n", "the first line must be `//@version=5`"),
    ("indicator('x')\nplot(close, 'c')\n", "the first line must be `//@version=5`"),
    ("//@version=5\nstrategy('x')\nplot(close, 'c')\n", "the script must declare `indicator(...)` (not a strategy or a library)"),
    (LIBRARY_SCRIPT, "the script must declare `indicator(...)` (not a strategy or a library)"),
    ("//@version=5\nplot(close, 'c')\n", "the script must declare `indicator(...)` (not a strategy or a library)"),
])
def test_a_script_of_the_wrong_shape_is_sent_back(pine, why):
    assert pa.script_problem(pine) == why


def test_a_script_of_the_right_shape_goes_on_to_the_engine_and_a_long_one_does_not():
    assert pa.script_problem(OK_SCRIPT) is None
    assert pa.script_problem("\r\n".join(OK_SCRIPT.split("\n"))) is None      # a Windows line ending is not a shape
    long = OK_SCRIPT + "// " + "x" * pa.SCRIPT_MAX_CHARS
    assert pa.script_problem(long).startswith("the script is ")
    assert pa.SCRIPT_MAX_CHARS < runtime_definitions.RUNTIME_MAX_DEFINITION_BYTES
