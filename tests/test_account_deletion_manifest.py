"""`docs/account-deletion-manifest.md` names EXACTLY the tables the account purge deletes.

Wave 7, lane J, item J4. The manifest was hand-typed beside the code it describes and, at
the wave-6 close, was 16 tables short of what `account_purge.purge_user_data` deletes -- 20
by wave 7, once lane G's email-in tables (`j2_inbound_addresses`, `j2_inbound_usage`,
`j2_inbound_drops`) and lane H's `j2_note_embeddings` landed. Its table is now GENERATED by
`tools/account_deletion_manifest.py` and never typed.

Three independent readings of "what the purge deletes", and they must agree:

* the DOC -- parsed here from its own markdown table rows;
* the RUNTIME -- `purge_user_data` run against an empty in-memory database reports, in
  `rows_deleted`, every table it issued a DELETE against (a missing table is a counted no-op);
* the DERIVATION -- the generator's AST read of `account_purge.py`.

A difference fails BY NAME, in either direction. Non-vacuity controls name `j2_notes` and the
indirect `j2_option_legs`, so an empty parse on either side cannot pass.
"""
from __future__ import annotations

import re
import sqlite3
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))

import account_deletion_manifest as gen  # noqa: E402

DOC = REPO / "docs" / "account-deletion-manifest.md"
_ROW = re.compile(r"^\|\s*`(j2_[a-z0-9_]+)`\s*\|")


def _doc_text() -> str:
    return DOC.read_text(encoding="utf-8").replace("\r\n", "\n")


def _doc_purged() -> set[str]:
    """The table names in the doc's manifest table (the generated block), read as markdown."""
    names = set()
    for line in gen.doc_block(_doc_text()).splitlines():
        m = _ROW.match(line)
        if m:
            names.add(m.group(1))
    return names


def _doc_not_purged() -> set[str]:
    """The names the doc's hand-written 'correctly NOT purged' section lists."""
    text = _doc_text()
    start = text.index("### Correctly NOT purged")
    nxt = text.find("\n## ", start)
    section = text[start: nxt if nxt != -1 else len(text)]
    return {m.group(1) for line in section.splitlines() if (m := _ROW.match(line))}


def _runtime_purged() -> set[str]:
    """Every table `purge_user_data` issues a DELETE against, read off its own report.

    An in-memory database has none of the tables, so every DELETE is a "no such table"
    no-op -- which the purge still records by name. The attachment half resolves under the
    repo-root conftest's sandbox pins and finds no directory for this id."""
    from api.services.journal_two import account_purge

    conn = sqlite3.connect(":memory:")
    try:
        report = account_purge.purge_user_data("j4-manifest-probe-no-such-user", conn)
    finally:
        conn.close()
    assert report["errors"] == [], report["errors"]
    return set(report["rows_deleted"])


def _diff(label_a: str, a: set[str], label_b: str, b: set[str]) -> str:
    lines = []
    for name in sorted(a - b):
        lines.append(f"  {name}: in {label_a}, NOT in {label_b}")
    for name in sorted(b - a):
        lines.append(f"  {name}: in {label_b}, NOT in {label_a}")
    return "\n".join(lines)


def test_the_manifest_names_exactly_the_tables_the_purge_deletes():
    doc, runtime = _doc_purged(), _runtime_purged()
    # Non-vacuity, by name, on BOTH sides.
    for name in ("j2_notes", "j2_option_legs"):
        assert name in runtime, f"the purge's own report does not name {name}: {sorted(runtime)}"
        assert name in doc, f"the doc's table does not name {name}"
    problem = _diff("the purge (runtime)", runtime, "docs/account-deletion-manifest.md", doc)
    assert not problem, ("the manifest and the purge disagree -- regenerate with "
                         "`python tools/account_deletion_manifest.py --write`:\n" + problem)


def test_the_derivation_reads_what_the_purge_runs():
    derived, runtime = gen.purged_tables(), _runtime_purged()
    problem = _diff("the purge (runtime)", runtime, "the generator's AST derivation", derived)
    assert not problem, problem
    indirect = {t: (fk, parent) for t, fk, parent in gen.derive()["indirect"]}
    assert indirect.get("j2_option_legs") == ("strategy_id", "j2_option_strategies")
    assert indirect.get("j2_broker_member_stale_notify") == ("broker_account_id", "j2_broker_accounts")


def test_the_generated_block_in_the_doc_is_current():
    """Owner keys and ownership are derived too -- not only the names."""
    assert gen.doc_block(_doc_text()) == gen.render(), (
        "docs/account-deletion-manifest.md is stale -- run "
        "`python tools/account_deletion_manifest.py --write`")


def test_what_the_doc_says_is_NOT_purged_really_is_not_and_the_code_says_why():
    not_purged, runtime = _doc_not_purged(), _runtime_purged()
    assert "j2_broker_digest_dedup" in not_purged, "non-vacuity: the not-purged section was not read"
    both = sorted(not_purged & runtime)
    assert not both, f"listed as NOT purged but the purge deletes them: {both}"
    src = gen.PURGE.read_text(encoding="utf-8")
    silent = sorted(n for n in not_purged if n not in src)
    assert not silent, f"excluded in the doc but account_purge.py does not say why: {silent}"


def test_every_member_table_the_schema_creates_is_purged_or_emptied_by_a_trigger():
    """Doc == code is not enough on its own: the CODE can be short of the SCHEMA. Every
    `j2_*` table `journal_two.db.ensure_schema` creates with a `user_id` column is either
    deleted by the purge, or emptied by an `AFTER DELETE` trigger on a table the purge
    deletes (the FTS mirrors) -- read from the schema's own trigger SQL, never listed here.
    Self-ensured tables (email-in, embeddings, reminders, weekly digest) are not created by
    `ensure_schema`; the doc-vs-purge rail above is what covers them."""
    from api.services.journal_two.db import ensure_schema

    conn = sqlite3.connect(":memory:")
    try:
        ensure_schema(conn)
        tables = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE 'j2\\_%' ESCAPE '\\'")]
        member = sorted(t for t in tables
                        if any(c[1] == "user_id" for c in conn.execute(f'PRAGMA table_info("{t}")')))
        triggers = conn.execute(
            "SELECT tbl_name, sql FROM sqlite_master WHERE type = 'trigger'").fetchall()
    finally:
        conn.close()
    purged = _runtime_purged()
    emptied_by = {}
    for base, sql in triggers:
        if base in purged and re.search(r"\bAFTER\s+DELETE\b", sql or "", re.IGNORECASE):
            for target in re.findall(r"DELETE\s+FROM\s+(\w+)", sql, re.IGNORECASE):
                emptied_by.setdefault(target, base)
    # Non-vacuity, by name: the schema was read, and the notes FTS mirror is seen as trigger-emptied.
    assert "j2_notes" in member, f"the schema read saw no j2_notes: {member[:5]}"
    assert emptied_by.get("j2_notes_fts") == "j2_notes", sorted(emptied_by)
    left = [t for t in member if t not in purged and t not in emptied_by]
    assert not left, ("tables holding a member's user_id that an account deletion leaves "
                      f"behind: {left} -- add them to account_purge._DIRECT_USER_TABLES")


