"""WHICH NUMBERS ARE A RUNNING VALUE'S OWN: one rule, in the door and in the window.

A running value's own numbers are not changed one at a time (ruling 2026-11-18): every number
inside several linked running values, and a one-value running value's gain (in the shape that can
settle) and warm-up. The door refuses a one-number edit of one (`running_value_owns`,
`_refuse_edits_inside_linked`); the window does not offer one as an Input (`derivedSettings.js`,
`runningValueOwns`).

TWO IMPLEMENTATIONS OF ONE RULE ARE HELD TOGETHER BY ONE LIST OF CASES:
`tests/fixtures/authoring/running_value_own_numbers.json`. It is WRITTEN from the door's answer
(`RUNNING_VALUE_OWN_WRITE=1 python -m pytest tests/test_running_value_own_numbers.py`), this file
fails when it is stale, and the window's own test reads the same file. So that the fixture is not
just the door agreeing with itself, the cases whose answer is known by construction are also
written out by hand below.
"""
from __future__ import annotations

import io
import json
import os
import pathlib

import pytest

from tests.test_converse_running_values_linked import CHOICE, CLOSE, FISHER, SMOOTHER, S, back, laguerre
from tests.test_p2_truth_server import call, conv, empty_view, env, num, op, out, view  # noqa: F401 -- fixtures by name

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "authoring" / "running_value_own_numbers.json"
SELF = S("self")
ATR = call("atr", S("high"), S("low"), S("close"), num(14))
SETTLING = call("accum", CLOSE, op("+", SELF, op("*", num(0.1), op("-", CLOSE, SELF))), num(300))
SETTLING_OTHER_ORDER = call("accum", CLOSE, op("+", op("*", op("-", call("sma", CLOSE, num(20)), SELF), num(0.25)), SELF), num(200))
STOP = call("accum", S("low"), call("max", SELF, op("-", CLOSE, op("*", num(3), ATR))), num(300))
STREAK = call("accum", num(0), op("?:", op(">", CLOSE, back(CLOSE, 1)), op("+", SELF, num(1)), num(0)), num(100))
SERIES_GAIN = call("accum", CLOSE, op("+", SELF, op("*", op("/", num(2), num(11)), op("-", CLOSE, SELF))), num(300))
# the thing it moves toward reads the value itself: NOT the shape that can settle, so the 0.5 is not a gain
READS_ITSELF = call("accum", CLOSE, op("+", SELF, op("*", num(0.5), op("-", op("+", CLOSE, SELF), SELF))), num(300))
TWO_POLE = call("accum2", num(1), num(300), CLOSE, CLOSE,
                op("+", op("*", num(0.2), CLOSE), op("-", op("*", num(1.4), S("state1")), op("*", num(0.6), S("state2")))), S("state1"))

CASES = [
    ("a one-value smoother in the shape that settles", SETTLING),
    ("the same shape, sum and product the other way round, reading an average", SETTLING_OTHER_ORDER),
    ("a stop that only rises", STOP),
    ("a streak", STREAK),
    ("a gain that is arithmetic, not one number", SERIES_GAIN),
    ("a multiple of something that reads the value itself", READS_ITSELF),
    ("a two-pole filter", TWO_POLE),
    ("a two-pole filter inside ordinary maths", op("-", back(CLOSE, 3), op("*", num(2), TWO_POLE))),
    ("a two-pole filter with its coefficients written as maths", SMOOTHER),
    ("a four-stage filter", laguerre()),
    ("a smoothed, stretched range position", FISHER),
    ("a choice inside a term that reads no running value", CHOICE),
    ("a one-value smoother beside an average", op("+", SETTLING, call("ema", CLOSE, num(50)))),
    ("no running value at all", op("-", call("ema", CLOSE, num(12)), call("ema", CLOSE, num(26)))),
]


def number_paths(tree):
    """Every plain number in a formula, as its `args` indices from the root."""
    found, stack = [], [(tree, [])]
    while stack:
        node, at = stack.pop()
        if not isinstance(node, dict):
            continue
        if node.get("type") == "num":
            found.append(at)
        for i, child in enumerate(node.get("args") or []):
            stack.append((child, at + [i]))
    return sorted(found)


def answered(conv):
    cases = []
    for name, tree in CASES:
        own, other = [], []
        for path in number_paths(tree):
            by = conv.running_value_owns(tree, path)
            (own.append({"path": path, "by": by}) if by else other.append(path))
        cases.append({"name": name, "tree": tree, "own": own, "other": other})
    return {"_": ("GENERATED by tests/test_running_value_own_numbers.py from the door's own answer "
                  "(RUNNING_VALUE_OWN_WRITE=1). Each case is a formula and, for every plain number in it, whether that number is "
                  "one of a running value's OWN (`own`: its path and the function that owns it) or an ordinary number (`other`). "
                  "The door's test fails when this is stale; the window's test (derivedSettings.test.js) answers the same cases."),
            "contract": "uct.running-value-own-numbers/1", "cases": cases}


def test_the_shared_cases_are_what_the_door_answers(conv):
    doc = answered(conv)
    text = json.dumps(doc, indent=1, ensure_ascii=False) + "\n"
    if os.environ.get("RUNNING_VALUE_OWN_WRITE") == "1":
        io.open(FIXTURE, "w", encoding="utf-8", newline="\n").write(text)
    on_file = json.loads(io.open(FIXTURE, encoding="utf-8").read())
    assert on_file == doc, "stale: RUNNING_VALUE_OWN_WRITE=1 python -m pytest tests/test_running_value_own_numbers.py"
    # NON-VACUITY: both answers occur, and both kinds of owner
    owners = {p["by"] for c in doc["cases"] for p in c["own"]}
    assert owners == {"accum", "accum2", "accum4"}
    assert sum(len(c["other"]) for c in doc["cases"]) > 10 and sum(len(c["own"]) for c in doc["cases"]) > 20


def test_the_answers_known_by_construction(conv):
    """Written out by hand, so the fixture is not only the door agreeing with itself."""
    owns = conv.running_value_owns
    # a one-value smoother `accum(close, self + 0.1 * (close - self), 300)`: the gain and the warm-up, nothing else
    assert owns(SETTLING, [1, 1, 0]) == "accum" and owns(SETTLING, [2]) == "accum"
    assert number_paths(SETTLING) == [[1, 1, 0], [2]]
    # the other order: accum(close, (sma(close, 20) - self) * 0.25 + self, 200)
    assert owns(SETTLING_OTHER_ORDER, [1, 0, 1]) == "accum" and owns(SETTLING_OTHER_ORDER, [2]) == "accum"
    assert owns(SETTLING_OTHER_ORDER, [1, 0, 0, 0, 1]) is None                   # the average's length is the member's
    # a stop that only rises: its warm-up only; the multiple and the ATR length are ordinary
    assert owns(STOP, [2]) == "accum"
    assert owns(STOP, [1, 1, 1, 0]) is None and owns(STOP, [1, 1, 1, 1, 3]) is None
    # a streak: its warm-up only (its 1 and 0 are ordinary numbers of the formula)
    assert [p for p in number_paths(STREAK) if owns(STREAK, p)] == [[2]]
    # a gain that is arithmetic (2 / 11) is not "one number": only the warm-up is its own
    assert [p for p in number_paths(SERIES_GAIN) if owns(SERIES_GAIN, p)] == [[2]]
    # `self + 0.5 * ((close + self) - self)`: what it moves toward reads the value itself, so this is not the
    # shape that can settle and the 0.5 is an ordinary number
    assert [p for p in number_paths(READS_ITSELF) if owns(READS_ITSELF, p)] == [[2]]
    assert owns(READS_ITSELF, [1, 1, 0]) is None
    # linked: every number, wherever it sits, and by the function that holds it
    assert all(owns(TWO_POLE, p) == "accum2" for p in number_paths(TWO_POLE)) and len(number_paths(TWO_POLE)) == 5
    assert all(owns(laguerre(), p) == "accum4" for p in number_paths(laguerre()))
    inside_maths = op("-", back(CLOSE, 3), op("*", num(2), TWO_POLE))
    assert owns(inside_maths, [1, 0]) is None                                     # the 2 outside it
    assert owns(inside_maths, [1, 1, 1]) == "accum2"                              # its warm-up
    # places this cannot follow are nobody's
    for nowhere in ([9], [0, "n"], [1, 5], [0, 0, 0], []):
        assert owns(inside_maths, nowhere) is None
    for not_a_tree in (None, 3, "x", []):
        assert owns(not_a_tree, [0]) is None


def test_the_door_sends_back_a_one_number_edit_of_a_one_value_running_values_own_number(conv):
    holding = view(1, [out("line", STOP, type_="series")])
    with pytest.raises(conv._Refused) as caught:
        conv.check_envelope(env(1, [{"op": "set_slot", "slot": "line#2", "value": 50}]), 1, holding)
    refused = caught.value
    assert refused.gate == "unsupported:running-value"
    assert "the running value's own gain or warm-up" in refused.detail
    assert "send the whole formula again with set_output_tree on output 'line'" in refused.detail
    assert "a running value's own number was changed on its own" in refused.reason and "accum" not in refused.reason
    # CONTROL: the multiple and the ATR length inside the same running value are ordinary edits
    conv.check_envelope(env(1, [{"op": "set_slot", "slot": "line#1.1.1.0", "value": 2}]), 1, holding)
    conv.check_envelope(env(1, [{"op": "set_slot", "slot": "line#1.1.1.1.3", "value": 21}]), 1, holding)
    # the gain of the shape that settles is its own; sent again whole, it is checked and noted afresh
    smooth = view(1, [out("line", SETTLING, type_="series")])
    with pytest.raises(conv._Refused):
        conv.check_envelope(env(1, [{"op": "set_slot", "slot": "line#1.1.0", "value": 0.001}]), 1, smooth)
    slower = call("accum", CLOSE, op("+", SELF, op("*", num(0.001), op("-", CLOSE, SELF))), num(300))
    again = conv.check_envelope(env(1, [{"op": "set_output_tree", "output": "line", "tree": slower}]), 1, smooth)
    (note,) = conv.running_value_notes(again)
    assert "so its counts and levels restart" in note["text"]                     # 0.001 no longer settles in 300 bars: said so
