def test_history_is_dated_append_only_and_first_write_wins(monkeypatch):
    receipt = _armed(monkeypatch)
    h = receipt["short_interest_history"]
    assert h["settlement_date"] == "2026-09-15"
    assert h["recorded"] == len(PARITY["tickers"]) + fv._MIN_ROWS
    # same settlement, a changed value on a later pull: the first row stands
    rows = [_fv_row(s) for s in PARITY["tickers"]]
    rows[0][3] = "5.00%"
    again = _pull(monkeypatch, rows, as_of="2026-09-30T06:45:00+00:00")
    assert again["short_interest_history"]["recorded"] == 0
    series = si.get_short_interest_history("AAPL")
    assert series == [{"settlement_date": "2026-09-15", "shares_short": round(0.0088 * 14.58e9),
                       "short_float_pct": 0.88, "short_ratio": 2.71, "pulled_at": PULL_ISO}]


