"""TERM-046 — short interest moves onto Finviz behind SHORT_INTEREST_SOURCE.

Recorded fixtures only, no network anywhere:
  * tests/fixtures/short_interest/yfinance_flag_off_golden.json — the exact bytes
    the PRE-TERM-046 get_short_interest produced (generated by exec'ing the base
    blob), which the flag-off path must still produce.
  * tests/fixtures/short_interest/parity_recorded.json — Finviz's own values and
    yfinance's .info for six tickers, recorded in the same minute on 2026-09-29.

The Finviz artifact is built through the REAL finviz_universe.run_pull (fetch
stubbed with the recorded cells), so the path under test is the one production
runs: export CSV -> _parse -> artifact -> short_interest.
"""
import json
import os
from datetime import date
from pathlib import Path

import pytest

from api.services import short_interest as si
from api.services import yf_util
from api.services.screener import finviz_universe as fv

FIX = Path(__file__).parent / "fixtures" / "short_interest"
GOLDEN = json.loads((FIX / "yfinance_flag_off_golden.json").read_text(encoding="utf-8"))
PARITY = json.loads((FIX / "parity_recorded.json").read_text(encoding="utf-8"))
PULL_ISO = "2026-09-29T06:45:03+00:00"      # 02:45 ET on the recording day
HEADERS = ["Ticker", "Shares Outstanding", "Shares Float", "Short Float", "Short Ratio"]


@pytest.fixture(autouse=True)
def _isolate(monkeypatch, tmp_path):
    monkeypatch.delenv("SHORT_INTEREST_SOURCE", raising=False)
    monkeypatch.setenv("SCREENER_FINVIZ_ARTIFACT", str(tmp_path / "screener_finviz.json"))
    monkeypatch.setenv("SHORT_INTEREST_HISTORY_DB_PATH", str(tmp_path / "si_hist.db"))
    monkeypatch.setattr(si, "_today_et", lambda: date(2026, 9, 29))
    si._CACHE = type(si._CACHE)()
    si._SNAP.update(key=None, snap=None)
    yield


def _fv_row(sym):
    p = PARITY["tickers"][sym]["finviz_quote_page"]
    return [sym, p["Shs Outstand"], p["Shs Float"], p["Short Float"], p["Short Ratio"]]


def _csv(rows):
    return "\n".join(",".join(r) for r in [HEADERS] + rows) + "\n"


def _pull(monkeypatch, rows, as_of=PULL_ISO):
    """The real run_pull, fetch stubbed; padded past _MIN_ROWS with filler."""
    filler = [[f"Z{i:04d}", "100.00M", "90.00M", "1.00%", "1.00"] for i in range(fv._MIN_ROWS)]
    monkeypatch.setattr(fv, "_fetch_finviz_csv_text", lambda: _csv(rows + filler))
    monkeypatch.setattr(fv, "_now_iso", lambda: as_of)
    si._SNAP.update(key=None, snap=None)
    return fv.run_pull()


def _stub_yf(monkeypatch, infos):
    current = {}

    def fake(fn, default, *a, **k):
        return infos.get(current["sym"])

    monkeypatch.setattr(yf_util, "bounded_call", fake)
    return current


# ── the flag ─────────────────────────────────────────────────────────────────

def test_the_default_source_is_yfinance_in_the_literal_and_the_behaviour(monkeypatch):
    assert si.SHORT_INTEREST_MODE_FLAGS["SHORT_INTEREST_SOURCE"][0] == "yfinance"
    assert si.source() == "yfinance"
    for junk in ("", "  ", "FINVIZZ", "finra", "1"):
        monkeypatch.setenv("SHORT_INTEREST_SOURCE", junk)
        assert si.source() == "yfinance", junk
    monkeypatch.setenv("SHORT_INTEREST_SOURCE", " Finviz ")
    assert si.source() == "finviz"


@pytest.mark.parametrize("env", [None, "", "not-a-source"])
@pytest.mark.parametrize("case", sorted(GOLDEN["golden"]))
def test_flag_off_is_byte_identical_to_the_pre_term046_code(monkeypatch, case, env, tmp_path):
    if env is not None:
        monkeypatch.setenv("SHORT_INTEREST_SOURCE", env)
    current = _stub_yf(monkeypatch, GOLDEN["infos"])
    touched = []
    monkeypatch.setattr(si, "_load_finviz_snapshot", lambda: touched.append(1))
    current["sym"] = (case or "").upper().strip()
    si._CACHE = type(si._CACHE)()
    assert json.dumps(si.get_short_interest(case)) == GOLDEN["golden"][case]
    assert not touched, "flag off must never read the Finviz artifact"
    assert not (tmp_path / "si_hist.db").exists(), "flag off must write no history"


def test_the_golden_is_not_vacuous():
    """Control: the golden covers every branch of the old function — data, both
    error shapes, the empty-ticker refusal — so byte-equality above means something."""
    g = GOLDEN["golden"]
    assert len(g) >= 15
    assert json.loads(g["AAPL"])["shares_short"] == 128753092
    assert json.loads(g["NONEINFO"])["error"].startswith("yfinance failed")
    assert json.loads(g["EMPTY"])["error"] == "no short interest data available"
    assert json.loads(g[""]) == {"error": "ticker required"}
    assert {json.loads(g[k])["crowded"] for k in ("AAPL", "MODERATE", "HIGH", "VHIGH")} == {
        "low", "moderate", "high", "very_high"}


# ── the Finviz path ─────────────────────────────────────────────────────────

def _armed(monkeypatch):
    monkeypatch.setenv("SHORT_INTEREST_SOURCE", "finviz")
    rows = [_fv_row(s) for s in PARITY["tickers"]]
    return _pull(monkeypatch, rows)


def test_finviz_path_keeps_every_consumer_field_and_reads_no_yfinance(monkeypatch):
    _armed(monkeypatch)
    monkeypatch.setattr(yf_util, "bounded_call",
                        lambda *a, **k: pytest.fail("finviz path must not call yfinance"))
    out = si.get_short_interest("aapl")
    old_keys = list(json.loads(GOLDEN["golden"]["AAPL"]))
    assert list(out)[:len(old_keys)] == old_keys, "shared keys, same order"
    assert out["short_pct_of_float"] == 0.88
    assert out["days_to_cover"] == 2.71
    assert out["shares_short"] == round(0.0088 * 14.58e9)
    assert out["crowded"] == "low"
    assert out["licensing_class"] == "LA"
    assert out["source"].startswith("finviz")
    assert out["shares_short_prior_month"] is None, "no history yet -> unknown, not zero"
    assert out["shares_short_change_pct"] is None


def test_as_of_is_the_settlement_date_never_the_pull_date(monkeypatch):
    receipt = _armed(monkeypatch)
    assert receipt["wrote"] is True
    for sym, rec in PARITY["tickers"].items():
        out = si.get_short_interest(sym)
        assert out["as_of_date"] == "2026-09-15", sym
        # ⭐ the inference agrees with FINRA's own date as Yahoo reports it
        assert out["as_of"] == rec["yfinance_info"]["dateShortInterest"], sym
        assert out["as_of_date"] != "2026-09-29"
        assert out["pulled_at"] == PULL_ISO
        assert "inferred" in out["as_of_basis"]


