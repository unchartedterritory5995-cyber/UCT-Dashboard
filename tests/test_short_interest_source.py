def test_prior_month_comes_only_from_recorded_history(monkeypatch):
    monkeypatch.setenv("SHORT_INTEREST_SOURCE", "finviz")
    # a month earlier: a pull that represents the 2026-08-14 settlement
    _pull(monkeypatch, [["AAPL", "14.61B", "14.58B", "0.80%", "2.50"]],
          as_of="2026-08-27T06:45:00+00:00")
    _armed(monkeypatch)
    out = si.get_short_interest("AAPL")
    prior = round(0.0080 * 14.58e9)
    assert out["shares_short_prior_month"] == prior
    assert out["shares_short_change_pct"] == round((round(0.0088 * 14.58e9) - prior) / prior * 100, 2)
    assert "shares_short_prior_month" in out["derived_fields"]


# ── parity, by field ────────────────────────────────────────────────────────

# Finviz (flag on) vs yfinance (flag off), on the frozen recording. Pinned as a
# table so the differences are a reviewed fact, not a summary percentage.
EXPECTED_PARITY = {
    #        short_pct_of_float  days_to_cover   shares_short (finviz derived, yahoo)
    "AAPL": ((0.88, 0.88), (2.71, 3.03), (128304000, 128753092)),
    "NVDA": ((1.27, 1.27), (2.36, 2.29), (294513000, 294225803)),
    "TSLA": ((2.44, 1.95), (1.76, 1.79), (68808000, 68862357)),
    "GME":  ((9.45, 8.4),  (5.76, 5.27), (39054015, 39069126)),
    "CVNA": ((9.25, 11.63), (6.95, 8.14), (62208100, 62226156)),
    "PLTR": ((2.72, 2.8),  (1.64, 2.08), (60112000, 60184903)),
}


def test_parity_by_field_on_recorded_fixtures(monkeypatch):
    _armed(monkeypatch)
    fin = {s: si.get_short_interest(s) for s in PARITY["tickers"]}
    monkeypatch.delenv("SHORT_INTEREST_SOURCE")
    current = _stub_yf(monkeypatch, {s: d["yfinance_info"] for s, d in PARITY["tickers"].items()})
    yah = {}
    for s in PARITY["tickers"]:
        current["sym"] = s
        si._CACHE = type(si._CACHE)()
        yah[s] = si.get_short_interest(s)
    got = {s: ((fin[s]["short_pct_of_float"], yah[s]["short_pct_of_float"]),
               (fin[s]["days_to_cover"], yah[s]["days_to_cover"]),
               (fin[s]["shares_short"], yah[s]["shares_short"])) for s in fin}
    assert got == EXPECTED_PARITY
    for s in fin:
        # derived shares short sits within Short Float's 2-decimal rounding of FINRA's
        rel = abs(fin[s]["shares_short"] - yah[s]["shares_short"]) / yah[s]["shares_short"]
        assert rel < 0.01, (s, rel)
        assert fin[s]["as_of"] == yah[s]["as_of"], s
        # Yahoo carries prior-month from FINRA; Finviz cannot until history exists
        assert yah[s]["shares_short_prior_month"] is not None
        assert fin[s]["shares_short_prior_month"] is None
        # Yahoo leaves % of shares outstanding empty on every recorded ticker
        assert yah[s]["short_pct_of_shares_outstanding"] is None
        assert fin[s]["short_pct_of_shares_outstanding"] is not None
