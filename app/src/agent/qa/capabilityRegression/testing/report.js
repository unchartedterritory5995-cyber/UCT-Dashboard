// CAPABILITY REGRESSION (Mission 2) — the generated coverage report (coverage/coverage.json + coverage/COVERAGE.md).
import { PROTECTIONS, totals, knownGaps } from './inventory'

const mark = (v) => (v === null ? '·' : v ? '✓' : '✗')
export function coverageJson(cov, contract, catalog) {
  return {
    generatedBy: 'app/src/agent/qa/capabilityRegression/inventory.test.js (UPDATE_CAPREG=1)',
    catalog: { all: catalog.all.length, withProductionKinds: catalog.prod.length, darkGated: catalog.all.length - catalog.prod.length },
    totals: totals(cov),
    knownGaps: knownGaps(),
    capabilities: Object.fromEntries(Object.entries(cov).map(([n, c]) => [n, { ...contract[n], ...c }])),
  }
}
export function coverageMd(j) {
  const t = j.totals
  const lines = [
    '# UCT Agent — capability regression coverage (generated)', '',
    '> Generated by `app/src/agent/qa/capabilityRegression/inventory.test.js` — `UPDATE_CAPREG=1 npx vitest run src/agent/qa/capabilityRegression/inventory.test.js`.',
    '> Do not edit by hand: the test fails when this file differs from the registry + corpus. Method: docs/agent/REGRESSION-SYSTEM.md.', '',
    `Catalog: **${j.catalog.all}** capabilities (every server-gated kind on; ${j.catalog.withProductionKinds} with production's data kinds). With at least one regression case beyond the pinned approval contract: **${t.withAnyRegressionCase} / ${t.capabilities}**.`, '',
    '| protection | covered / applicable |', '|---|---|',
    ...PROTECTIONS.map(p => `| ${p} | ${t.perProtection[p].covered} / ${t.perProtection[p].applicable} |`), '',
    `## Known gaps (${j.knownGaps.length})`, '', '| id | level | intent | phrasing | owner | reason |', '|---|---|---|---|---|---|',
    ...j.knownGaps.map(g => `| ${g.id} | ${g.level} | ${g.intent} | ${g.phrasing ? `"${g.phrasing}"` : '—'} | ${g.owner} | ${String(g.reason).replace(/\|/g, '/')} |`), '',
    '## Per capability', '', `✓ covered · ✗ not covered · · not applicable. Columns: ${PROTECTIONS.join(', ')}.`, '',
    `| capability | group | risk | undo | ${PROTECTIONS.join(' | ')} |`, `|---|---|---|---|${PROTECTIONS.map(() => '---').join('|')}|`,
    ...Object.entries(j.capabilities).map(([n, c]) => `| ${n} | ${c.group ?? '—'} | ${c.risk} | ${c.undo ?? '—'} | ${PROTECTIONS.map(p => mark(c.protections[p])).join(' | ')} |`), '',
  ]
  return lines.join('\n')
}
