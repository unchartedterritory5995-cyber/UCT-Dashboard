//
// ─── ⭐ A FORMULA THAT IS A CHECKED LIBRARY INDICATOR, RECOGNISED BY ITS SHAPE (2026-11-18) ───
//
// ⚰️ READ IN THE LIVE WINDOW. A Kaufman Adaptive Moving Average built from the library showed
// "Inputs 8": every number in its formula, among them "2 plus 1 amount" and "2 divided by (30 plus
// 1) divisor". On Balance Volume showed one input, "0 minus Volume amount". The library declares
// three settings for the first and none for the second. And it was a correctness hazard, not only
// untidy: KAMA's efficiency length sits in two places, so changing one input alone made a different
// indicator under the same name.
//
// THE RULE. The window holds the library's public half (`checkedLibrary.json`, GENERATED by
// `tools/named_indicators_build.py`; never edited by hand). A formula IS a library output when it
// has that output's shape: the same tree, the same numbers everywhere except where a declared
// setting sits, and ONE number for a setting in every place it sits. This is the door's own rule
// (`api/services/named_indicators.py`, `output_in`), ported, and one shared list of cases is run by
// both (`tests/fixtures/authoring/checked_library_cases.json`) so the two cannot drift.
//
// ⛔ STORE NOTHING (the engine owner's rule for settings, `derivedSettings.js`). Nothing marks a
// saved indicator as "from the library": it is recognised from its own formula each time it is
// read. So there is nothing to migrate, and a formula edited until it no longer has the shape is
// simply the member's own formula again.

import LIBRARY from './checkedLibrary.json'

const isObj = (v) => !!v && typeof v === 'object' && !Array.isArray(v)

/** Every library indicator the window knows: `{id, name, version, params, outputs}`. */
export const CHECKED_LIBRARY = Object.freeze(LIBRARY.indicators)

const sameBound = (a, b) => a[0] === b[0] && a[1] === b[1]

/** Is `node` an acceptable number for `param` where the library holds `lib`? → ['num', v] | ['input', name] | null */
function siteValue(node, lib, param, inputs) {
  if (!isObj(node)) return null
  if (lib.type === 'num' && node.type === 'series' && inputs.has(node.name)) return ['input', node.name]   // the member's own setting drives it
  if (node.type !== lib.type) return null
  const v = node.value
  if (typeof v !== 'number' || !Number.isFinite(v)) return null
  if (param.integer && !Number.isInteger(v)) return null
  if (v < param.min || v > param.max) return null
  return ['num', v]
}

function same(node, lib, path, sites, params, inputs, bound, places) {
  if (!isObj(node) || !isObj(lib)) return false
  const key = sites.get(path.join('.'))
  if (key !== undefined) {
    const got = siteValue(node, lib, params.get(key), inputs)
    if (!got) return false
    if (bound.has(key)) { if (!sameBound(bound.get(key), got)) return false } else bound.set(key, got)   // one setting is ONE number, everywhere
    if (got[0] === 'num') places.push({ key, path, offset: lib.type !== 'num' })
    if (lib.type === 'num') return true                                    // a number: nothing beneath it
    if (node.type !== lib.type || node.name !== lib.name) return false
  } else if (node.type !== lib.type || node.name !== lib.name || node.value !== lib.value) {
    return false
  }
  const a = Array.isArray(node.args) ? node.args : []
  const b = Array.isArray(lib.args) ? lib.args : []
  return a.length === b.length && a.every((x, i) => same(x, b[i], [...path, i], sites, params, inputs, bound, places))
}

const TABLES = CHECKED_LIBRARY.flatMap((entry) => entry.outputs.map((output) => ({
  entry, output,
  params: new Map(entry.params.map((p) => [p.key, p])),
  sites: new Map(Object.entries(output.sites || {}).flatMap(([key, paths]) => paths.map((p) => [p.join('.'), key]))),
})))

/** The library output `node` IS, whole: `{entry, output, values, places}`; null when it is none. */
function partAt(node, inputs) {
  for (const t of TABLES) {
    const bound = new Map()
    const places = []
    if (same(node, t.output.tree, [], t.sites, t.params, inputs, bound, places)) {
      return {
        entry: t.entry, output: t.output,
        // each setting's number as found; null when one of the member's own inputs drives it
        values: Object.fromEntries([...bound].map(([k, v]) => [k, v[0] === 'num' ? v[1] : null])),
        places,
      }
    }
  }
  return null
}

const inputSet = (inputs) => new Set(Array.isArray(inputs) ? inputs.filter((k) => typeof k === 'string') : [])

/**
 * Every library output `tree` holds, OUTERMOST FIRST and never one inside another (a signal line
 * holds the line it smooths: that is the signal line, not also the line).
 * `tree` is the formula in the form its slots are read from (`collapseExpansions`).
 * @returns {Array<{entry, output, at: number[], values: object, places: Array<{key, path: number[], offset: boolean}>}>}
 *   `at` is the part's place in the tree; each place's `path` is from the TREE's root.
 */
export function libraryParts(tree, inputs = []) {
  const declared = inputSet(inputs)
  const out = []
  const walk = (node, at) => {
    if (!isObj(node)) return
    const part = partAt(node, declared)
    if (part) {
      out.push({ ...part, at, places: part.places.map((p) => ({ ...p, path: [...at, ...p.path] })) })
      return
    }
    if (Array.isArray(node.args)) node.args.forEach((a, i) => walk(a, [...at, i]))
  }
  walk(tree, [])
  return out
}

/** The library output the WHOLE `tree` is, or null. */
export function libraryOutputOf(tree, inputs = []) {
  const part = isObj(tree) ? partAt(tree, inputSet(inputs)) : null
  return part ? { ...part, at: [] } : null
}

const plain = (v) => (Number.isInteger(v) ? String(v) : String(Number(v.toFixed(6))))

/** A part's settings in words, in the entry's own order: "efficiency length 10, fast length 2". */
export function settingsWords(part) {
  return part.entry.params
    .filter((p) => typeof part.values[p.key] === 'number')
    .map((p) => `${p.label.toLowerCase()} ${plain(part.values[p.key])}`).join(', ')
}

const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()

/** The library indicator a title names, by the indicator's own full name; null when it names none. */
export function namedByTitle(title) {
  const t = norm(title)
  return (t && CHECKED_LIBRARY.find((e) => norm(e.name) === t)) || null
}
