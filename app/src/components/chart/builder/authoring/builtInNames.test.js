// app/src/components/chart/builder/authoring/builtInNames.test.js
//
// ─── THE NAMES ON THE INDICATORS LIST, AS THE REGISTRY SERVES THEM ────────────────────
//
// `builtInNames.json` is GENERATED here from the running native registry: one row per built-in
// definition, `{id, name, shortName}`. It exists for one reader, the server-side census
// (`tests/test_built_in_names_census.py`), which asks the Create Indicator door how it takes
// "Add <name>" for EVERY built-in and holds that none is refused as an unknown name or improvised.
// The door is Python and the registry is JavaScript: this file is how the names cross, and the
// byte-for-byte test below is what keeps a built-in that is added, renamed or removed from passing
// unseen (the census then names it).
//
// Regenerate after a change to the registry's definitions:
//   (cd app && WRITE_BUILT_IN_NAMES=1 npx vitest run src/components/chart/builder/authoring/builtInNames.test.js)
//
// Also held here, where the registry runs: every library built-in name (`checkedLibrary.json`,
// `builtIns`) offers the registry's OWN name for the definition it adds. A definition may be
// DECLARED twice in the source (an older and a newer version, each with its own name); which one is
// served is only known here.

import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import * as registry from '../../engine/nativeRegistry'
import { BUILT_IN_NAMES } from './checkedLibrary'

const FILE = path.resolve(process.cwd(), 'src/components/chart/builder/authoring/builtInNames.json')
const LF = String.fromCharCode(10)

/** The built-in definitions the registry serves (a member's own `u_` definitions are not built-ins). */
function rowsOf(definitions) {
  return definitions
    .filter((d) => d && typeof d.id === 'string' && !d.id.startsWith('u_') && d.meta && typeof d.meta.name === 'string')
    .map((d) => ({ id: d.id, name: d.meta.name, shortName: typeof d.meta.shortName === 'string' ? d.meta.shortName : '' }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
}
const served = () => rowsOf(registry.listDefinitions())

const text = () => `${JSON.stringify({
  _: 'GENERATED by builtInNames.test.js from the native registry (WRITE_BUILT_IN_NAMES=1). Do not edit. '
    + 'Read by tests/test_built_in_names_census.py.',
  contract: 'uct.built-in-names/1',
  names: served(),
}, null, 1)}${LF}`

describe('builtInNames.json is the registry\'s own list', () => {
  it('regenerates byte-for-byte (WRITE_BUILT_IN_NAMES=1 rewrites it)', () => {
    if (process.env.WRITE_BUILT_IN_NAMES === '1') fs.writeFileSync(FILE, text())
    const committed = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n/g, LF) : ''
    expect(committed === text(),
      'builtInNames.json is stale: a built-in was added, renamed or removed. Regenerate it '
      + '(WRITE_BUILT_IN_NAMES=1, see this file\'s header) and run tests/test_built_in_names_census.py: '
      + 'a new built-in must be classified there.').toBe(true)
  })

  it('every row is a definition with a name, each id once', () => {
    const rows = served()
    expect(rows.length).toBeGreaterThan(40)
    expect(new Set(rows.map((r) => r.id)).size).toBe(rows.length)
    for (const r of rows) {
      expect(r.name.trim(), r.id).toBe(r.name)
      expect(r.name.length, r.id).toBeGreaterThan(1)
    }
  })

  it("a member's own definition is never a row (they share the registry with the built-ins)", () => {
    const mine = { id: 'u_0123abcd', meta: { name: 'My own', shortName: 'Mine' } }
    const builtIn = { id: 'zzBuiltIn', meta: { name: 'Built in', shortName: 'BI' } }
    expect(rowsOf([mine, builtIn, { id: 'noName', meta: {} }, null])).toEqual([{ id: 'zzBuiltIn', name: 'Built in', shortName: 'BI' }])
    expect(served().some((r) => r.id.startsWith('u_'))).toBe(false)
  })
})

describe('a library built-in name offers the registry\'s own name', () => {
  it('each row names a served definition, by the name the registry serves it under', () => {
    const byId = new Map(served().map((r) => [r.id, r]))
    expect(BUILT_IN_NAMES.length).toBeGreaterThan(10)
    for (const b of BUILT_IN_NAMES) {
      const def = byId.get(b.indicator)
      expect(def, `${b.id}: no built-in ${b.indicator} in the registry`).toBeTruthy()
      expect(b.builtInName, b.id).toBe(def.name)
    }
  })

  it('a built-in the library offers by its own name is offered under exactly that name', () => {
    // the entries added for the names on the Indicators list (`builtin_*`): the member typed the list's
    // name, so the entry's name IS the registry's name (no second name to drift)
    const own = BUILT_IN_NAMES.filter((b) => String(b.id).startsWith('builtin_'))
    expect(own.length).toBeGreaterThanOrEqual(10)
    for (const b of own) expect(b.name, b.id).toBe(b.builtInName)
  })
})
