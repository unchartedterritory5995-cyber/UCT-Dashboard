//
// ─── ⭐⭐ THE HOST LANE'S KNOWN-DIVERGENCE LIST (owner decision 2026-11-17) ──────────────
//
// We serve only what a reference sentence states or a committed capture grading MATCH
// witnesses; otherwise we refuse BY NAME. The runtime lane has its committed kill list
// (`runtimeKill.js`, `api/data/pine_runtime_killlist.json`); this is the HOST lane's twin.
// Every script with a committed TradingView capture that grades DIVERGE on the production
// (host) lane is listed by the sha256 of its source, and the host doors refuse it by name:
//   · the member preview   `memberPaneDefinition` (before the host lane is asked);
//   · the install door     `nativeRegistry.validateUserDefinitions` (the server stamps a
//                          served row `meta.hostKnownDivergence`; this file is asked too).
// The server's doors (save, served rows, alerts, scans, backtests) read the same file:
// `api/services/host_known_divergence.py`.
//
// ⛔ ONE AUTHORITY: `hostKnownDivergence.json` beside this file, imported here and read by
// the server, GENERATED by `tools/vendor_harness/host_divergence.py --write` and re-derived
// both ways by `tests/test_pine_host_known_divergence.py`. Never hand-typed.
// ⛔ A REFUSAL IS NEVER A DELETE: a saved copy stays in the store and comes back the moment
// its script is unlisted.
// ⛔ THE MEASURING SUITES MEASURE THE ENGINE, NOT THIS LIST (`src/test-setup.js` calls
// `__ignoreHostKnownDivergenceForTests`): the vendor harness grades what the host lane WOULD
// draw, which is what keeps the list derivable (a list that refused its own evidence would
// lift itself), and the census applies the list in its predicate
// (`tools/pine_coverage/coverage_map.py`). The list itself is railed with it reset
// (`hostKnownDivergence.test.js`). In the app it is ON: nothing outside a test calls the seam.
import LIST from './hostKnownDivergence.json'
import { sha256Hex } from './ast/parse.js'

/** The stable refusal code (registered in `supportLoop/refusalCodes.json`). */
export const HOST_KNOWN_DIVERGENCE_GUARD = 'pine:known-divergence'
/** The served-row stamp the install door refuses (`host_known_divergence.STAMP`). */
export const HOST_KNOWN_DIVERGENCE_STAMP = 'hostKnownDivergence'

const HASH_RE = /^[0-9a-f]{64}$/

function entriesOf(doc) {
  const m = new Map()
  for (const s of (doc && Array.isArray(doc.scripts) ? doc.scripts : [])) {
    if (s && typeof s.sha256 === 'string' && HASH_RE.test(s.sha256)) m.set(s.sha256, s)
  }
  return m
}

const COMMITTED = entriesOf(LIST)
let _entries = COMMITTED
let _ignored = false

/** The listed hashes (tests, diagnostics). */
export function hostKnownDivergenceList() {
  return [..._entries.keys()]
}

/** What a member reads: what differs on which captured chart, and that it is withheld until that is fixed
 *  (the server's `host_known_divergence.sentence`, the same words without the code prefix). */
export function hostKnownDivergenceSentence(entry) {
  return `this script is not drawn: ${entry.reason}. It is withheld until that is fixed, and comes back `
    + 'once a new comparison against TradingView matches.'
}

/** Why this Pine source is refused on the host lane, `{guard, reason, slug}`, or null.
 *  @param {string} source */
export function hostKnownDivergenceOf(source) {
  if (_ignored || typeof source !== 'string' || !source || !_entries.size) return null
  let e = _entries.get(sha256Hex(source))
  if (!e && source.includes('\r\n')) e = _entries.get(sha256Hex(source.replace(/\r\n/g, '\n')))
  if (!e) return null
  return { guard: HOST_KNOWN_DIVERGENCE_GUARD, reason: hostKnownDivergenceSentence(e), slug: e.slug }
}

/** Rails only (`src/test-setup.js`): the measuring suites grade the engine, not this list. */
export function __ignoreHostKnownDivergenceForTests() { _ignored = true }
/** Rails only: back to the app's state (the committed list, ON). */
export function __resetHostKnownDivergence() { _ignored = false; _entries = COMMITTED }
/** Rails only: a synthetic list (`{scripts: [...]}`), ON. */
export function __setHostKnownDivergenceForTests(doc) { _ignored = false; _entries = entriesOf(doc) }
/** Rails only: is the list consulted? */
export function hostKnownDivergenceActive() { return !_ignored }
