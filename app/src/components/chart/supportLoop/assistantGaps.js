// app/src/components/chart/supportLoop/assistantGaps.js
//
// ─── ⭐ WHAT A MEMBER STILL CANNOT GET FROM A SCRIPT: ASKED OF THE ENGINE (2026-11-19) ───
//
// The assistant writes Pine now, so what stands between a request and an indicator is what the
// ENGINE does with the script. This module turns a list of probes (the smallest script that shows
// each thing a member might ask for: `assistantGapProbes.json`) into the engine's own answer for
// each, by running it through the member's paste path. The committed result
// (`assistantGaps.json`) is what `docs/pine/assistant-writes-pine/GAPS.md` is written from
// (`api/services/pine_authoring.py::gaps_document`, which adds the server's admission for a script
// the bar-by-bar lane draws).
//
// ⛔ CAPABILITIES, NOT REQUESTS. A probe is a script and a plain description of what it draws. No
// member's wording, no answer and no count of anything lives here: the repository is public, and
// what a live round found stays in the private report.
//
// `assistantPineReference.test.js` regenerates the file and fails when the committed bytes differ,
// so the day the engine serves a probe its row leaves GAPS.md in the same change.

import { RUNS_STATES } from './assistantPineReference'

export const GAP_KINDS = Object.freeze(['output', 'calculation', 'drawing', 'data', 'language'])

const clean = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim()

/**
 * @param {object} args
 * @param {Array<{id, cannot, kind, source}>} args.probes
 * @param {(source: string) => {ok, lane, state, headline, guard, family, why}} args.verdictOf
 */
export function buildAssistantGaps({ probes = [], verdictOf }) {
  const rows = probes.map((p) => {
    const v = verdictOf(p.source) || {}
    const runs = v.ok === true && RUNS_STATES.includes(v.state)
    return {
      id: p.id, kind: p.kind, cannot: p.cannot, source: p.source,
      runs, lane: v.lane || 'host', state: v.state || 'unknown', headline: clean(v.headline),
      ...(runs ? {} : { guard: v.guard || null, family: v.family || null, why: clean(v.why).slice(0, 400) }),
    }
  })
  return {
    _comment: 'GENERATED by app/src/components/chart/supportLoop/assistantPineReference.test.js '
      + '(WRITE_ASSISTANT_PINE_REFERENCE=1). Do not edit by hand. The engine\'s own verdict on each gap probe '
      + '(assistantGapProbes.json). Read by api/services/pine_authoring.py to write docs/pine/assistant-writes-pine/GAPS.md.',
    version: 1,
    probes: rows,
  }
}
