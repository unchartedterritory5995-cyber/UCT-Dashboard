"""Both scan corpora's expectations as criteria LEAVES, compiled by the Screener's own grammar (owner: agent-sc).

The browser-side intent layer (app/src/agent/capabilities/scanIntent.js) is measured in vitest, which cannot run the
Screener's Python grammar. This module compiles every expected `criteria_text` once, through `grammar.compile_text`,
into expected_leaves.json, so the JS measurement compares against the grammar's own reading and never a second
parser. `tests/test_uct_agent_scan_intent_expected.py` fails if the file is not current.

    python -m api.services.uct_agent.scan.eval.expected --write
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "expected_leaves.json"


def _leaves(text: str) -> list[dict]:
    from api.services.screener import grammar, logic
    if not (text or "").strip():
        return []
    out = grammar.compile_text(text)
    node = out["logic"]
    if node is None:
        return []
    if not (("key" in node) or (set(node) == {"all"} and all("key" in c for c in node["all"]))):
        raise ValueError(f"only a flat AND is supported here: {text}")
    return list(logic.leaves(node))


def _entry(expect: dict, tolerance: dict | None = None) -> dict:
    kind = expect["type"]
    e: dict = {"kind": kind}
    if kind == "spec":
        e["leaves"] = _leaves(expect.get("criteria_text") or "")
        e["sort"] = expect.get("sort")
    elif kind == "ask":
        e["slot"] = expect.get("slot")
    elif kind == "refuse":
        e["reason"] = expect.get("reason")
    if tolerance:
        e["tolerance"] = tolerance
    return e


def build() -> dict:
    os.environ.setdefault("SCREENER_LOGIC_ENABLED", "1")
    disc = json.loads((HERE / "discovery.json").read_text(encoding="utf-8"))
    sc2 = json.loads((HERE / "sc2.json").read_text(encoding="utf-8"))
    d = {}
    for q in disc["questions"]:
        if q["expect_refusal"]:
            d[q["id"]] = {"text": q["question"], **_entry({"type": "refuse", "reason": q.get("refusal_reason")})}
        else:
            d[q["id"]] = {"text": q["question"],
                          **_entry({"type": "spec", "criteria_text": q["expect"]["criteria_text"]}, q.get("tolerance"))}
    s = {i["id"]: {"text": i["text"], **_entry(i["expect"])} for i in sc2["items"]}
    chains = [{"id": c["id"], "steps": [{"text": st["text"], "delta": st["delta"], **_entry(st["expect"])} for st in c["steps"]]}
              for c in sc2["chains"]]
    return {"about": "generated by api/services/uct_agent/scan/eval/expected.py (--write); do not edit by hand",
            "discovery_version": disc["version"], "sc2_version": sc2["version"],
            "discovery": d, "sc2": s, "sc2_chains": chains}


def text() -> str:
    return json.dumps(build(), indent=1, ensure_ascii=False, sort_keys=False) + "\n"


if __name__ == "__main__":
    if "--write" in sys.argv:
        OUT.write_text(text(), encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")
    else:
        sys.stdout.write(text())
